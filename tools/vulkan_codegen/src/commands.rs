use crate::registry::{method_name, rust_type, snake, Command, Field, Registry};
use std::collections::BTreeMap;

pub fn emit(r: &Registry, roots: &BTreeMap<String, String>) -> String {
    let mut out = String::from("// Generated by makepad-vulkan-codegen.\nuse crate::vk::*;\nuse core::ffi::CStr;\n");
    for name in roots.keys() {
        let c = r.command(name);
        let params: Vec<String> = c.fields.iter().map(|f|f.ty.clone()).collect();
        out.push_str(&format!("pub type Pfn{} = unsafe extern \"system\" fn({}) -> {};\n",name.trim_start_matches("vk"),params.join(", "), ret_type(&c)));
    }
    for group in ["entry", "instance", "device"] { table(&mut out,r,roots,group); }
    for (name, group) in roots {
        if name == "vkGetInstanceProcAddr" || name == "vkGetDeviceProcAddr" { continue; }
        wrapper(&mut out,r,&r.command(name),group);
    }
    out
}
fn ret_type(c: &Command) -> &str { if c.ret == "core::ffi::c_void" { "()" } else { &c.ret } }
fn table(out: &mut String, r: &Registry, roots: &BTreeMap<String,String>, group: &str) {
    let title = match group { "entry"=>"Entry", "instance"=>"Instance", _=>"Device" };
    out.push_str(&format!("#[derive(Clone)]\npub struct {title}Table {{\n"));
    for (n,g) in roots { if g == group { out.push_str(&format!("    pub {}: Option<Pfn{}>,\n",snake(&n[2..]),&n[2..])); } }
    out.push_str("}\n");
    let (params, call) = match group {
        "entry" => ("get: PfnGetInstanceProcAddr", "get(Instance::null(), name.as_ptr())"),
        "instance" => ("handle: Instance, get: PfnGetInstanceProcAddr", "get(handle, name.as_ptr())"),
        _ => ("handle: Device, get: PfnGetDeviceProcAddr", "get(handle, name.as_ptr())"),
    };
    out.push_str(&format!("impl {title}Table {{ pub unsafe fn load({params}) -> Self {{\n    let lookup = |name: &CStr| {call};\n    Self {{\n"));
    for (name,g) in roots {
        if g != group { continue; }
        let mut lookup = format!("lookup(c\"{name}\")");
        for (alias,c) in &r.commands {
            if c.alias == *name && (alias.ends_with("KHR") || alias.ends_with("EXT")) {
                lookup.push_str(&format!(".or_else(|| lookup(c\"{alias}\"))"));
            }
        }
        out.push_str(&format!("        {}: core::mem::transmute::<PfnVoidFunction, Option<Pfn{}>>({lookup}),\n",snake(&name[2..]),&name[2..]));
    }
    out.push_str("    }\n} }\n");
}
fn argument_name(f: &Field) -> String {
    f.name.strip_prefix("pp_").or_else(||f.name.strip_prefix("p_")).unwrap_or(&f.name).into()
}
fn pointee(f: &Field) -> String {
    f.ty.strip_prefix("*mut ").or_else(||f.ty.strip_prefix("*const ")).unwrap().to_string()
}
fn has_next(r: &Registry, f: &Field) -> bool {
    r.types.get(&f.base).is_some_and(|t|t.fields.iter().any(|f| f.name == "p_next"))
}
fn wrapper(out: &mut String, r: &Registry, c: &Command, group: &str) {
    if c.name == "vkGetQueryPoolResults" { query_results(out); return; }
    let owner = match group { "entry"=>"Entry", "instance"=>"Instance", _=>"Device" };
    let field_name = snake(&c.name[2..]);
    let method = method_name(&c.name);
    let return_result = c.ret == "Result";
    let fields = &c.fields;
    let last = fields.last().unwrap();
    let enumeration = last.pointer == 1 && !last.constant && last.len.starts_with('p')
        && fields.iter().any(|p| p.name == snake(&last.len) && p.pointer == 1);
    let array_out = last.pointer == 1 && !last.constant && !last.len.is_empty() && !enumeration;
    let output = (return_result || c.ret == "core::ffi::c_void") && last.pointer > 0 && !last.constant && !has_next(r,last)
        && !matches!(c.name.as_str(), "vkUpdateDescriptorSets") || enumeration || array_out;
    let output_type = if output { pointee(last) } else { "()".into() };
    let mut signature: Vec<String> = Vec::new();
    let mut args: Vec<String> = Vec::new();
    let mut setup = String::new();
    let mut lengths: BTreeMap<String, String> = BTreeMap::new();
    for f in fields {
        if !f.len.is_empty() && f.len != "null-terminated" && !f.len.contains("::") && !f.len.contains("->") {
            lengths.entry(snake(f.len.split(',').next().unwrap())).or_insert(argument_name(f));
        }
    }
    for (i,f) in fields.iter().enumerate() {
        let name = argument_name(f);
        if i == 0 && (f.base == "VkDevice" && group == "device" || f.base == "VkInstance" && group == "instance") {
            args.push("self.handle".into()); continue;
        }
        if enumeration && f.name == snake(&last.len) { args.push("&mut count".into()); continue; }
        if output && i == fields.len()-1 { args.push(if array_out || enumeration { "values.as_mut_ptr()" } else { "&mut value" }.into()); continue; }
        if let Some(array) = lengths.get(&f.name) {
            if f.pointer == 0 { args.push(format!("{array}.len() as _")); continue; }
        }
        if c.name == "vkEnumerateDeviceExtensionProperties" && f.name == "p_layer_name" { args.push("core::ptr::null()".into()); continue; }
        let mut ty = f.ty.clone();
        let mut arg = name.clone();
        if f.base == "VkBool32" { ty = "bool".into(); arg = format!("{name} as u32"); }
        if f.pointer != 0 {
            if f.base == "VkAllocationCallbacks" {
                ty = "Option<&AllocationCallbacks>".into();
                arg = format!("{name}.map_or(core::ptr::null(), |v| v as *const AllocationCallbacks)");
            } else if f.base == "char" && f.len == "null-terminated" {
                if f.optional {
                    ty = "Option<&CStr>".into(); arg = format!("{name}.map_or(core::ptr::null(), CStr::as_ptr)");
                } else { ty = "&CStr".into(); arg = format!("{name}.as_ptr()"); }
            } else if !f.len.is_empty() && f.base == "void" && f.constant && f.pointer == 1 {
                // A sized byte blob (push constants, buffer updates).
                ty = "&[u8]".into();
                arg = format!("{name}.as_ptr().cast()");
            } else if !f.len.is_empty() && f.base != "void" {
                ty = format!("&{}[{}]", if f.constant {""} else {"mut "},pointee(f));
                arg = format!("{name}.as_{}ptr()", if f.constant {""} else {"mut_"});
            } else if f.base.starts_with("Vk") && f.pointer == 1 {
                ty = format!("&{}{}",if f.constant {""} else {"mut "},rust_type(&f.base));
            }
        }
        signature.push(format!("{name}: {ty}")); args.push(arg);
    }
    let mut result_type = if output { output_type.clone() } else { "()".into() };
    if !output && !return_result && c.ret != "core::ffi::c_void" { result_type = c.ret.clone(); }
    if output && last.base == "VkBool32" { result_type = "bool".into(); }
    if array_out || enumeration { result_type = format!("Vec<{output_type}>"); }
    if c.name == "vkCreateInstance" { result_type = "crate::Instance".into(); }
    if c.name == "vkCreateDevice" { result_type = "crate::Device".into(); }
    if c.name == "vkAcquireNextImageKHR" { result_type = "(u32, bool)".into(); }
    if c.name == "vkQueuePresentKHR" || c.name == "vkGetFenceStatus" { result_type = "bool".into(); }
    let error = if c.name == "vkCreateGraphicsPipelines" { "(Vec<Pipeline>, Result)" } else { "Result" };
    let ret = if return_result { format!("std::result::Result<{result_type}, {error}>") } else { result_type };
    let comma = if signature.is_empty() { "" } else { ", " };
    out.push_str(&format!("impl crate::{owner} {{\n    #[inline]\n    pub unsafe fn {method}(&self{comma}{}) -> {ret} {{\n        let call = self.table.{field_name}.expect(\"{name} is unavailable\");\n",signature.join(", "),name=c.name));
    if enumeration {
        enumerate(out,c,&args,&output_type,return_result);
        out.push_str("    }\n}\n"); return;
    }
    if array_out {
        let len = if last.len.contains("::") || last.len.contains("->") {
            let path = last.len.replace("->", "::");
            let parts: Vec<&str> = path.split("::").collect();
            format!("{}.{} as usize",snake(parts[0]).trim_start_matches("p_"),snake(parts[1]))
        } else { format!("{}.len()",lengths[&snake(&last.len)]) };
        setup.push_str(&format!("        let mut values: Vec<{output_type}> = Vec::with_capacity({len});\n        values.resize({len}, {output_type}::default());\n"));
    } else if output {
        let default = if output_type.starts_with("*mut") { "core::ptr::null_mut()".into() } else { format!("{output_type}::default()") };
        setup.push_str(&format!("        let mut value: {output_type} = {default};\n"));
    }
    out.push_str(&setup);
    let call = format!("call({})",args.join(", "));
    let expr = if c.name == "vkCreateInstance" { "crate::Instance::from_handle(self, value)" }
        else if c.name == "vkCreateDevice" { "crate::Device::from_handle(self, value)" }
        else if array_out { "values" } else if output && last.base == "VkBool32" { "value != 0" }
        else if output { "value" } else { "()" };
    match c.name.as_str() {
        "vkGetFenceStatus" => out.push_str(&format!("        match {call} {{ Result::SUCCESS => Ok(true), Result::NOT_READY => Ok(false), code => Err(code) }}\n")),
        "vkAcquireNextImageKHR" => out.push_str(&format!("        match {call} {{ Result::SUCCESS => Ok((value, false)), Result::SUBOPTIMAL_KHR => Ok((value, true)), code => Err(code) }}\n")),
        "vkQueuePresentKHR" => out.push_str(&format!("        match {call} {{ Result::SUCCESS => Ok(false), Result::SUBOPTIMAL_KHR => Ok(true), code => Err(code) }}\n")),
        "vkCreateGraphicsPipelines" => out.push_str(&format!("        match {call} {{ Result::SUCCESS => Ok(values), code => Err((values, code)) }}\n")),
        _ if return_result => out.push_str(&format!("        {call}.result()?;\n        Ok({expr})\n")),
        _ if c.ret != "core::ffi::c_void" => out.push_str(&format!("        {call}\n")),
        _ => out.push_str(&format!("        {call};\n        {expr}\n")),
    }
    out.push_str("    }\n}\n");
}
fn enumerate(out: &mut String, c: &Command, args: &[String], element: &str, result: bool) {
    let mut first = args.to_vec();
    *first.last_mut().unwrap() = "core::ptr::null_mut()".into();
    out.push_str("        loop {\n            let mut count = 0u32;\n");
    let initial = format!("call({})",first.join(", "));
    if result { out.push_str(&format!("            {initial}.result()?;\n")); }
    else { out.push_str(&format!("            {initial};\n")); }
    out.push_str(&format!("            let mut values: Vec<{element}> = Vec::with_capacity(count as usize);\n            values.resize(count as usize, {element}::default());\n"));
    let second = format!("call({})",args.join(", "));
    if result {
        out.push_str(&format!("            let code = {second};\n            if code == Result::INCOMPLETE {{ continue; }}\n            code.result()?;\n            values.truncate(count as usize);\n            return Ok(values);\n"));
    } else { out.push_str(&format!("            {second};\n            values.truncate(count as usize);\n            return values;\n")); }
    out.push_str("        }\n");
    let _ = c;
}
fn query_results(out: &mut String) {
    out.push_str("impl crate::Device {\n    pub unsafe fn get_query_pool_results(&self, pool: QueryPool, first: u32, values: &mut [u64], flags: QueryResultFlags) -> std::result::Result<(), Result> {\n        let call = self.table.get_query_pool_results.expect(\"vkGetQueryPoolResults is unavailable\");\n        call(self.handle, pool, first, values.len() as u32, core::mem::size_of_val(values), values.as_mut_ptr().cast(), core::mem::size_of::<u64>() as u64, flags).result()\n    }\n}\n");
}
