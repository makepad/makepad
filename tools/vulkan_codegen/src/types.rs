use crate::registry::{rust_type, snake, Field, Registry, Type};
use std::collections::{BTreeMap, BTreeSet};

pub fn emit(r: &Registry, selected: &BTreeSet<String>, constants: &BTreeSet<String>, wanted: &BTreeMap<String, BTreeSet<String>>) -> String {
    let mut out = format!("// Generated by makepad-vulkan-codegen from Vulkan registry 1.4.{}.\n// Edit the generator/API roots, then regenerate.\nuse core::ffi::CStr;\n", r.revision);
    let mut constants = constants.clone();
    let mut wanted = wanted.clone();
    for name in selected {
        for f in &r.types[name].fields {
            if f.array.starts_with("VK_") { constants.insert(f.array.clone()); }
            if !f.value.is_empty() {
                wanted.entry(f.base.clone()).or_default().insert(member_name(&f.base, &f.value));
            }
        }
    }
    for name in constants {
        // The VK_MAKE_API_VERSION macros: API_VERSION_1_<minor>.
        if let Some(minor) = name.strip_prefix("VK_API_VERSION_1_").and_then(|m| m.parse::<u32>().ok()) {
            out.push_str(&format!("pub const API_VERSION_1_{minor}: u32 = (1 << 22) | ({minor} << 12);\n"));
            continue;
        }
        let value = r.value(&name);
        let short = name.strip_prefix("VK_").unwrap();
        let short = short.strip_suffix("_EXTENSION_NAME").map(|s| format!("{s}_NAME")).unwrap_or_else(|| short.to_string());
        if value.starts_with('"') {
            let text = value.trim_matches('"');
            out.push_str(&format!("pub const {short}: &CStr = c{value};\n"));
            assert!(!text.contains('\\'));
        } else {
            let (ty, value) = constant_expr(&value);
            out.push_str(&format!("pub const {short}: {ty} = {value};\n"));
        }
    }
    for name in selected {
        let t = &r.types[name];
        if t.category == "enum" && name.contains("FlagBits") { continue; }
        let n = rust_type(name);
        if t.category.is_empty() && n != *name && !name.starts_with("wl_") { continue; }
        if !t.alias.is_empty() { out.push_str(&format!("pub type {n} = {};\n", rust_type(&t.alias))); continue; }
        match t.category.as_str() {
            "basetype" => {
                let base = if t.base.is_empty() { "core::ffi::c_void".into() } else { rust_type(&t.base) };
                out.push_str(&format!("pub type {n} = {base};\n"));
            }
            "handle" => handle(&mut out, t),
            "enum" | "bitmask" => integer(&mut out, r, t, wanted.get(name)),
            "struct" | "union" => record(&mut out, t, selected, r),
            "funcpointer" => callback(&mut out, t),
            "" => out.push_str(&format!("pub type {n} = core::ffi::c_void;\n")),
            kind => panic!("unsupported selected type {name}: {kind}"),
        }
    }
    out.push_str("fn debug_flags(f: &mut core::fmt::Formatter<'_>, mut rest: u64, known: &[(u64, &str)]) -> core::fmt::Result {\n    let mut separator = \"\";\n    for &(bit, name) in known {\n        if bit != 0 && rest & bit == bit { f.write_str(separator)?; f.write_str(name)?; separator = \" | \"; rest &= !bit; }\n    }\n    if rest != 0 { f.write_str(separator)?; core::fmt::Binary::fmt(&rest, f)?; }\n    Ok(())\n}\n");
    out.push_str("// Every Vulkan extension record starts with this repr(C) header.\nunsafe fn append_extension(mut last: *mut BaseOutStructure, tail: *const core::ffi::c_void) {\n    while !(*last).p_next.is_null() { last = (*last).p_next; }\n    (*last).p_next = tail as *mut BaseOutStructure;\n}\n");
    out
}
pub fn constant_expr(value: &str) -> (&str, String) {
    match value {
        "(~0U)" => ("u32", "u32::MAX".into()),
        "(~1U)" => ("u32", "u32::MAX - 1".into()),
        "(~2U)" => ("u32", "u32::MAX - 2".into()),
        "(~0ULL)" => ("u64", "u64::MAX".into()),
        _ if value.ends_with('F') && value.contains('.') => ("f32", value.trim_end_matches('F').into()),
        _ => ("u32", value.trim_end_matches('U').into()),
    }
}
fn handle(out: &mut String, t: &Type) {
    let n = rust_type(&t.name);
    let repr = if t.dispatchable { "usize" } else { "u64" };
    out.push_str(&format!("#[repr(transparent)]\n#[derive(Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]\npub struct {n}(pub {repr});\nimpl {n} {{\n    pub const fn null() -> Self {{ Self(0) }}\n    pub const fn from_raw(value: u64) -> Self {{ Self(value as {repr}) }}\n    pub const fn as_raw(self) -> u64 {{ self.0 as u64 }}\n}}\n"));
    out.push_str(&format!("impl core::fmt::Debug for {n} {{ fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {{ f.write_str(\"0x\")?; core::fmt::LowerHex::fmt(&self.0, f) }} }}\n"));
}
fn value_name(group: &str, raw: &str) -> String {
    let mut group = snake(group.strip_prefix("Vk").unwrap()).to_ascii_uppercase();
    for suffix in ["_KHR", "_EXT", "_ANDROID", "_NV", "_AMD"] {
        if group.ends_with(suffix) { group.truncate(group.len()-suffix.len()); break; }
    }
    group = group.replace("_FLAG_BITS", "");
    let prefix = if group == "RESULT" { "VK_".to_string() } else { format!("VK_{group}_") };
    let Some(short) = raw.strip_prefix(&prefix) else { return String::new(); };
    let mut name = short.to_ascii_uppercase();
    name = name.replace("_BIT_", "_");
    if name.ends_with("_BIT") { name.truncate(name.len()-4); }
    if name.as_bytes().first().is_some_and(u8::is_ascii_digit) { name.insert_str(0,"TYPE_"); }
    name
}
fn member_name(group: &str, raw: &str) -> String {
    let mut name = value_name(group, raw);
    for suffix in ["KHR", "EXT", "ANDROID", "NV", "AMD"] {
        if group.ends_with(suffix) && name.ends_with(&format!("_{suffix}")) {
            name.truncate(name.len()-suffix.len()-1);
        }
    }
    name
}
fn integer(out: &mut String, r: &Registry, t: &Type, wanted: Option<&BTreeSet<String>>) {
    let n = rust_type(&t.name);
    let bitmask = t.category == "bitmask";
    let repr = if bitmask { if t.base.contains("Bits2") { "u64" } else { "u32" } } else { "i32" };
    let group = if bitmask { &t.base } else { &t.name };
    // Flag types are plain newtypes like every other integer type (rustc
    // checks them ~2.8x faster than bitflags! invocations). Every bit is
    // kept, so `!`, from_raw and driver-reported bits keep the raw value
    // exactly as the old ash wrappers did.
    out.push_str(&format!("#[repr(transparent)]\n#[derive(Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]\npub struct {n}(pub {repr});\nimpl {n} {{\n    pub const fn from_raw(value: {repr}) -> Self {{ Self(value) }}\n    pub const fn as_raw(self) -> {repr} {{ self.0 }}\n"));
    let mut emitted: BTreeSet<String> = BTreeSet::new();
    let mut debug_values: BTreeMap<String, String> = BTreeMap::new();
    for (raw, value) in &r.values {
        if &value.group != group { continue; }
        let short = member_name(group, raw);
        if short.is_empty() { continue; }
        let literal = r.value(raw);
        let needed = wanted.is_some_and(|w| w.contains(&short)) || t.name == "VkResult";
        if needed && emitted.insert(short.clone()) {
            out.push_str(&format!("    pub const {short}: Self = Self({literal} as {repr});\n"));
        }
        if t.name != "VkStructureType" || needed { debug_values.entry(literal).or_insert(short); }
    }
    if let Some(wanted) = wanted {
        for w in wanted { assert!(emitted.contains(w), "missing {}::{w}", t.name); }
    }
    if bitmask {
        out.push_str(&format!("    #[inline]\n    pub const fn from_bits_retain(value: {repr}) -> Self {{ Self(value) }}\n    #[inline]\n    pub const fn bits(self) -> {repr} {{ self.0 }}\n    #[inline]\n    pub const fn empty() -> Self {{ Self(0) }}\n    #[inline]\n    pub const fn all() -> Self {{ Self(!0) }}\n    #[inline]\n    pub const fn is_empty(self) -> bool {{ self.0 == 0 }}\n    #[inline]\n    pub const fn is_all(self) -> bool {{ self.0 == !0 }}\n    #[inline]\n    pub const fn contains(self, other: Self) -> bool {{ self.0 & other.0 == other.0 }}\n    #[inline]\n    pub const fn intersects(self, other: Self) -> bool {{ self.0 & other.0 != 0 }}\n}}\n"));
        for (op, method, sign) in [("BitOr", "bitor", "|"), ("BitAnd", "bitand", "&"), ("BitXor", "bitxor", "^")] {
            out.push_str(&format!("impl core::ops::{op} for {n} {{ type Output = Self; #[inline] fn {method}(self, other: Self) -> Self {{ Self(self.0 {sign} other.0) }} }}\nimpl core::ops::{op}Assign for {n} {{ #[inline] fn {method}_assign(&mut self, other: Self) {{ self.0 {sign}= other.0 }} }}\n"));
        }
        out.push_str(&format!("impl core::ops::Not for {n} {{ type Output = Self; #[inline] fn not(self) -> Self {{ Self(!self.0) }} }}\n"));
    } else {
        out.push_str("}\n");
    }
    out.push_str(&format!("impl core::fmt::Debug for {n} {{ fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {{\n"));
    if !bitmask {
        out.push_str("match self.0 {\n");
        for (value, name) in debug_values { out.push_str(&format!("    {value} => f.write_str(\"{name}\"),\n")); }
        out.push_str("    _ => core::fmt::Debug::fmt(&self.0, f),\n}\n");
    } else {
        let mut bits: Vec<(u64, String)> = debug_values.into_iter().map(|(value, name)| {
            let value = value.trim_end_matches('U');
            let number = if let Some(hex) = value.strip_prefix("0x") { u64::from_str_radix(hex,16) } else { value.parse::<u64>() }.expect("flag value");
            (number,name)
        }).collect();
        bits.sort_by_key(|v|v.0);
        out.push_str("debug_flags(f, self.0 as u64, &[\n");
        for (value, name) in bits {
            if value == 0 { continue; }
            out.push_str(&format!("({value}, \"{name}\"),\n"));
        }
        out.push_str("])\n");
    }
    out.push_str("} }\n");
    if t.name == "VkResult" {
        out.push_str("impl core::fmt::Display for Result { fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result { core::fmt::Debug::fmt(self, f) } }\nimpl std::error::Error for Result {}\nimpl Result { pub fn result(self) -> std::result::Result<(), Self> { if self == Self::SUCCESS { Ok(()) } else { Err(self) } } }\n");
    }
}
fn record(out: &mut String, t: &Type, selected: &BTreeSet<String>, r: &Registry) {
    let n = rust_type(&t.name);
    let derives = if t.name == "VkExtent2D" { "Clone, Copy, Debug, PartialEq, Eq" }
        else if t.category == "union" { "Clone, Copy" } else { "Clone, Copy, Debug" };
    out.push_str(&format!("#[repr(C)]\n#[derive({derives})]\npub {} {n} {{\n",t.category));
    for f in &t.fields {
        assert!(!f.ty.contains("UNSUPPORTED_BITFIELD"), "unsupported bitfield {}.{}",t.name,f.name);
        out.push_str(&format!("    pub {}: {},\n", f.name, f.ty));
    }
    out.push_str("}\n");
    out.push_str(&format!("impl Default for {n} {{ fn default() -> Self {{\n"));
    if let Some(f) = t.fields.iter().find(|f| !f.value.is_empty()) {
        let value = r.value(&f.value);
        out.push_str(&format!("    let mut value: Self = unsafe {{ core::mem::zeroed() }};\n    value.{} = {}({value});\n    value\n",f.name,rust_type(&f.base)));
    } else { out.push_str("    unsafe { core::mem::zeroed() }\n"); }
    out.push_str("} }\n");
    out.push_str(&format!("unsafe impl Send for {n} {{}}\nunsafe impl Sync for {n} {{}}\n"));
    if t.category == "union" {
        out.push_str(&format!("impl core::fmt::Debug for {n} {{ fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {{ f.write_str(\"{n}\") }} }}\n"));
        return;
    }
    out.push_str(&format!("impl {n} {{\n"));
    for f in &t.fields {
        setter(out, t, f);
        if f.base == "char" && !f.array.is_empty() {
            out.push_str(&format!("    pub fn {field}_as_c_str(&self) -> std::result::Result<&CStr, core::ffi::FromBytesUntilNulError> {{\n        let bytes = unsafe {{ core::slice::from_raw_parts(self.{field}.as_ptr().cast::<u8>(), self.{field}.len()) }};\n        CStr::from_bytes_until_nul(bytes)\n    }}\n",field=f.name));
        }
    }
    if let Some(next_field) = t.fields.iter().find(|f| f.name == "p_next") {
        for child in selected.iter().map(|n| &r.types[n]).filter(|child| child.extends.contains(&t.name)) {
            let child_n = rust_type(&child.name);
            assert!(child.fields.iter().any(|f|f.name == "p_next"), "missing pNext in {}", child.name);
            out.push_str(&format!("    #[inline]\n    pub fn next_{}(mut self, next: &mut {child_n}) -> Self {{ unsafe {{ append_extension((next as *mut {child_n}).cast(), self.p_next.cast()); }} self.p_next = next as *mut {child_n} as {}; self }}\n",snake(&child_n),next_field.ty));
        }
    }
    out.push_str("}\n");
}
fn setter(out: &mut String, parent: &Type, f: &Field) {
    if f.name == "s_type" || f.name == "p_next" { return; }
    let mut param = f.ty.clone();
    let mut assign = "value".to_string();
    let mut prefix = String::new();
    let mut name = f.name.clone();
    if f.pointer == 0 {
        if f.base == "VkBool32" { param = "bool".into(); assign = "value as u32".into(); }
    } else {
        name = name.strip_prefix("pp_").or_else(||name.strip_prefix("p_")).unwrap_or(&name).into();
        if f.len == "null-terminated" && f.base == "char" && f.pointer == 1 {
            param = "&CStr".into(); assign = "value.as_ptr()".into();
        } else if parent.name == "VkShaderModuleCreateInfo" && f.name == "p_code" {
            param = "&[u32]".into(); assign = "value.as_ptr()".into(); prefix = "self.code_size = core::mem::size_of_val(value); ".into();
        } else if !f.len.is_empty() {
            let count = snake(f.len.split(',').next().unwrap());
            if !parent.fields.iter().any(|v| v.name == count) { return; }
            let element = f.ty.strip_prefix("*const ").or_else(||f.ty.strip_prefix("*mut ")).unwrap_or_else(||panic!("invalid pointer field {}: {:?}", parent.name, f));
            if element == "core::ffi::c_void" { return; }
            let writable = !f.constant;
            param = format!("&{}[{element}]",if writable {"mut "} else {""});
            assign = format!("value.as_{}ptr()",if writable {"mut_"} else {""});
            prefix = format!("self.{count} = value.len() as _; ");
        } else if f.base.starts_with("Vk") && f.pointer == 1 {
            param = format!("&{}{}",if f.constant {""} else {"mut "},rust_type(&f.base));
        }
    }
    out.push_str(&format!("    #[inline]\n    pub fn {name}(mut self, value: {param}) -> Self {{ {prefix}self.{} = {assign}; self }}\n",f.name));
}
fn callback(out: &mut String, t: &Type) {
    let params: Vec<String> = t.fields.iter().map(|f| f.ty.clone()).collect();
    let ret = if t.ret == "core::ffi::c_void" { "()" } else { &t.ret };
    out.push_str(&format!("pub type {} = Option<unsafe extern \"system\" fn({}) -> {ret}>;\n",rust_type(&t.name),params.join(", ")));
}
