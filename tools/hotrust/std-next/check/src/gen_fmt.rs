//! Generates core/fmt/num/impls.rs: the per-type integer formatting impls.

pub fn run(core: &str) {
    let mut s = String::new();
    s.push_str("//! GENERATED by tools/hotrust/std-next/check/src/gen_fmt.rs (`hotrust-std-gen fmt ../core`); do not edit.\n\n");
    s.push_str("use super::super::{Binary, Debug, Display, Formatter, LowerHex, Octal, Result, UpperHex};\n");
    s.push_str("use super::{fmt_radix_u128, fmt_radix_u64, fmt_u128, fmt_u64};\n");
    // (type, unsigned twin, wide)
    let types = [
        ("i8", "u8", false), ("i16", "u16", false), ("i32", "u32", false), ("i64", "u64", false),
        ("isize", "usize", false), ("i128", "u128", true),
        ("u8", "u8", false), ("u16", "u16", false), ("u32", "u32", false), ("u64", "u64", false),
        ("usize", "usize", false), ("u128", "u128", true),
    ];
    for (t, u, wide) in types {
        let signed = t.starts_with('i');
        let (dec, radix, cast) = if wide { ("fmt_u128", "fmt_radix_u128", "u128") } else { ("fmt_u64", "fmt_radix_u64", "u64") };
        s.push('\n');
        if signed {
            s.push_str(&format!(
                "impl Display for {t} {{\n    fn fmt(&self, f: &mut Formatter<'_>) -> Result {{\n        {dec}(self.unsigned_abs() as {cast}, *self >= 0, f)\n    }}\n}}\n"
            ));
        } else {
            s.push_str(&format!(
                "impl Display for {t} {{\n    fn fmt(&self, f: &mut Formatter<'_>) -> Result {{\n        {dec}(*self as {cast}, true, f)\n    }}\n}}\n"
            ));
        }
        s.push_str(&format!(
            "impl Debug for {t} {{\n    fn fmt(&self, f: &mut Formatter<'_>) -> Result {{\n        if f.debug_lower_hex() {{\n            LowerHex::fmt(self, f)\n        }} else if f.debug_upper_hex() {{\n            UpperHex::fmt(self, f)\n        }} else {{\n            Display::fmt(self, f)\n        }}\n    }}\n}}\n"
        ));
        let bits = if signed { format!("*self as {u} as {cast}") } else { format!("*self as {cast}") };
        for (tr, shift, upper) in [("LowerHex", 4, false), ("UpperHex", 4, true), ("Octal", 3, false), ("Binary", 1, false)] {
            s.push_str(&format!(
                "impl {tr} for {t} {{\n    fn fmt(&self, f: &mut Formatter<'_>) -> Result {{\n        {radix}({bits}, {shift}, {upper}, f)\n    }}\n}}\n"
            ));
        }
    }
    let path = format!("{}/fmt/num/impls.rs", core);
    std::fs::create_dir_all(format!("{}/fmt/num", core)).unwrap();
    std::fs::write(&path, s).unwrap();
    eprintln!("wrote {}", path);
}
