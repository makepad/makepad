//! Third-party proc macros under the two policies (relax-compiler pmhost.rs): the test writes a
//! workspace into a temp folder whose macro crates are registry packages of a vendored crates-io
//! directory (nothing is downloaded), and runs it under `Policy::Open` (bare `relax`'s) and under
//! `Policy::Sandboxed` (`makepad`'s): this binary re-executes itself as the runner with each host.
//!
//! - bypass: one macro per route around the old token scan (std::os paths, file-system methods of
//!   `Path`, grouped and renamed imports of std, `r#std`, `#[path]` and `include!` files, a
//!   `macro_rules!` pasting `std::$m`, a macro crate's code generated by another macro crate, a
//!   declared C function). Under Open each one acts (its marker file appears, or it reports what
//!   it read); under Sandboxed each one fails at its call site naming the C function its code
//!   reached, and no marker appears.
//! - positive: macros in the shapes of the ecosystem's base crates (raw-pointer buffers and an
//!   interner in `unsafe`, thread-locals, HashMap, OnceLock, catch_unwind, TokenStream parsing,
//!   the crate's cargo environment), a workspace macro crate using a registry crate (confined
//!   too) and a workspace-only macro crate reading a file (host code): the same output under both.
//! - warm: the positive app under Sandboxed with the disk cache, started again after an edit of
//!   the app (its macros expand again): the macro world's code, its twins included, all comes from
//!   the world's cache (hits, no miss, nothing compiled), and the output is the same.
use std::path::{Path, PathBuf};
use std::process::Command;

const AS_RUNNER: &str = "RELAX_CONFINED_MACROS_RUNNER";

fn main() {
    // the runner, with the host of the policy asked for
    if let Ok(policy) = std::env::var(AS_RUNNER) {
        std::env::remove_var(AS_RUNNER);
        let host: &'static relax_runner::Host = match policy.as_str() {
            "open" => Box::leak(Box::new(relax_runner::Host { proc_macros: relax_compiler::pmhost::Policy::Open, ..makepad_run::HOST })),
            _ => &makepad_run::HOST,
        };
        relax_runner::main(host);
        return;
    }
    // a workspace per policy (its own marker folder), the four runs at once, and beside them the
    // cached workspace's two starts
    let t = std::env::temp_dir().join(format!("confined-macros-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&t);
    let (open, sandboxed, cached) = (t.join("open"), t.join("sandboxed"), t.join("cached"));
    let (ws_open, ws_sb, ws_cached) = (workspace(&open), workspace(&sandboxed), workspace(&cached));
    let ([bypass_open, positive_open, bypass_sb, positive_sb], (cold, warm)) = std::thread::scope(|s| {
        let runs = [(&ws_open, "open", "bypass"), (&ws_open, "open", "positive"), (&ws_sb, "sandboxed", "bypass"), (&ws_sb, "sandboxed", "positive")].map(|(ws, policy, package)| s.spawn(move || run(ws, policy, package, false)));
        let starts = s.spawn(|| {
            let cold = run(&ws_cached, "sandboxed", "positive", true);
            let main = ws_cached.join("positive/src/main.rs");
            let text = std::fs::read_to_string(&main).unwrap();
            std::fs::write(&main, format!("{text}// edited: its macros expand again\n")).unwrap();
            (cold, run(&ws_cached, "sandboxed", "positive", true))
        });
        (runs.map(|r| r.join().unwrap()), starts.join().unwrap())
    });
    let markers_after_sandboxed: Vec<String> = BYPASS.iter().filter(|b| sandboxed.join("markers").join(b.name).exists()).map(|b| b.name.to_string()).collect();
    let mut bad = Vec::new();
    // Open: every bypass acts
    if !bypass_open.0 {
        bad.push(format!("bypass under Open failed:\n{}\n{}", bypass_open.1, bypass_open.2));
    }
    for b in BYPASS {
        if b.marker && !open.join("markers").join(b.name).exists() {
            bad.push(format!("{}: no marker under Open (the fixture did not act)", b.name));
        }
    }
    if !bypass_open.1.contains("read_dir saw secret-entry") {
        bad.push(format!("read_dir: under Open it did not read the folder:\n{}", bypass_open.1));
    }
    // Sandboxed: every bypass is refused at its call site, naming the C function, and none acts
    if bypass_sb.0 {
        bad.push(format!("bypass under Sandboxed ran:\n{}", bypass_sb.1));
    }
    for b in BYPASS {
        let named = bypass_sb.2.lines().any(|l| l.contains(&format!("`{}_go`", b.name)) && l.contains("reaches the C function `"));
        if !named {
            bad.push(format!("{}: no named refusal under Sandboxed", b.name));
        }
    }
    if !markers_after_sandboxed.is_empty() {
        bad.push(format!("markers under Sandboxed: {:?}", markers_after_sandboxed));
    }
    if bypass_sb.1.contains("secret-entry") || bypass_sb.2.contains("secret-entry") {
        bad.push("read_dir: the folder's entry reached the output under Sandboxed".to_string());
    }
    // positive: the same output under both
    if !positive_open.0 || !positive_sb.0 {
        bad.push(format!("positive failed:\nOpen: {}\n{}\nSandboxed: {}\n{}", positive_open.1, positive_open.2, positive_sb.1, positive_sb.2));
    } else if positive_open.1 != positive_sb.1 || !positive_sb.1.contains("caught true") {
        bad.push(format!("positive differs:\nOpen:\n{}\nSandboxed:\n{}", positive_open.1, positive_sb.1));
    }
    // warm: the world's code from its cache (the boot trace's world cache line and macro host line)
    if !cold.0 || !warm.0 {
        bad.push(format!("cached starts failed:\ncold: {}\n{}\nwarm: {}\n{}", cold.1, cold.2, warm.1, warm.2));
    } else {
        if warm.1 != positive_sb.1 {
            bad.push(format!("warm output differs:\n{}\nuncached:\n{}", warm.1, positive_sb.1));
        }
        let world = warm.2.lines().find_map(|l| l.split_once("world cache: ")).map_or("(no world cache line)", |(_, w)| w);
        let n: Vec<u64> = world.split(|c: char| !c.is_ascii_digit()).filter_map(|x| x.parse().ok()).collect();
        if n.len() < 2 || n[0] == 0 || n[1] != 0 {
            bad.push(format!("warm start: the macro world's code is not all from its cache: {world}"));
        }
        if !warm.2.lines().any(|l| l.contains("proc-macro host: ") && l.contains("JIT compile 0 fns")) {
            let host = warm.2.lines().find(|l| l.contains("proc-macro host: ")).unwrap_or("(no proc-macro host line)");
            bad.push(format!("warm start: the macro world compiled code: {host}"));
        }
    }
    let _ = std::fs::remove_dir_all(&t);
    if !bad.is_empty() {
        eprintln!("confined_macros: FAILED\n{}", bad.join("\n"));
        std::process::exit(1);
    }
    println!("confined_macros: ok ({} bypass fixtures refused under Sandboxed and live under Open; positive output equal; warm start: {})", BYPASS.len(), warm.2.lines().find_map(|l| l.split_once("world cache: ")).map_or("", |(_, w)| w));
}

/// `run --quiet <package>` in the workspace under the policy: (success, stdout, stderr). `cached`:
/// with the disk cache (the workspace's own) and the boot trace, else without the cache.
fn run(ws: &Path, policy: &str, package: &str, cached: bool) -> (bool, String, String) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut c = Command::new(std::env::current_exe().unwrap());
    if cached {
        c.env("RELAX_BOOT_TRACE", "1").env_remove("RELAX_CACHE");
    } else {
        c.env("RELAX_CACHE", "off");
    }
    let out = c
        .args(["run", "--quiet", package])
        .current_dir(ws)
        .env(AS_RUNNER, policy)
        .env("CARGO_NET_OFFLINE", "true")
        .env("RELAX_STD", root.join("libs/relax/compiler/std"))
        .env_remove("CARGO")
        .output()
        .unwrap();
    (out.status.success(), String::from_utf8_lossy(&out.stdout).into_owned(), String::from_utf8_lossy(&out.stderr).into_owned())
}

