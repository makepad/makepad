/// The workspace: `bypass` and `positive` apps, two workspace macro crates and the vendored
/// registry packages.
fn workspace(t: &Path) -> PathBuf {
    let ws = t.join("ws");
    let markers = t.join("markers");
    let secret = t.join("secret");
    std::fs::create_dir_all(&markers).unwrap();
    std::fs::create_dir_all(&secret).unwrap();
    std::fs::write(secret.join("secret-entry"), "").unwrap();
    let put = |rel: &str, text: &str| {
        let p = ws.join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, text).unwrap();
    };
    put("Cargo.toml", "[workspace]\nresolver = \"2\"\nmembers = [\"bypass\", \"positive\", \"path_confined\", \"path_reads\"]\n");
    put(".cargo/config.toml", "[source.crates-io]\nreplace-with = \"v\"\n[source.v]\ndirectory = \"vendor\"\n");
    let package = |name: &str, deps: &str, proc_macro: bool| format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n{}[dependencies]\n{deps}", if proc_macro { "[lib]\nproc-macro = true\n" } else { "" });
    let vendored = |name: &str, deps: &str, files: &[(&str, String)]| {
        put(&format!("vendor/{name}/Cargo.toml"), &package(name, deps, true));
        put(&format!("vendor/{name}/.cargo-checksum.json"), "{\"files\":{},\"package\":null}");
        for (rel, text) in files {
            put(&format!("vendor/{name}/{rel}"), text);
        }
    };
    // bypass
    let mut deps = String::new();
    let mut uses = String::new();
    let mut prints = String::new();
    for b in BYPASS {
        let crate_name = format!("bypass_{}", b.name);
        let files: Vec<(&str, String)> = b
            .files
            .iter()
            .map(|(rel, text)| {
                let text = text.replace("MARKER", &markers.join(b.name).to_string_lossy()).replace("SECRET", &secret.to_string_lossy());
                (*rel, if *rel == "src/lib.rs" { format!("{HEAD}{text}") } else { text })
            })
            .collect();
        vendored(&crate_name, if b.name == "generated" { "bypass_stage1 = \"0.1.0\"\n" } else { "" }, &files);
        deps.push_str(&format!("{crate_name} = \"0.1.0\"\n"));
        uses.push_str(&format!("{crate_name}::{}_go!();\n", b.name));
        prints.push_str(&format!("    println!(\"{{}}\", {});\n", b.name.to_uppercase()));
    }
    vendored("bypass_stage1", "", &[("src/lib.rs", format!("{HEAD}#[proc_macro]\npub fn write_marker(_: TokenStream) -> TokenStream {{\n    \"std::fs::write(\\\"{}\\\", \\\"x\\\").unwrap();\".parse().unwrap()\n}}\n", markers.join("generated").to_string_lossy()))]);
    put("bypass/Cargo.toml", &package("bypass", &deps, false));
    put("bypass/src/main.rs", &format!("{uses}\nfn main() {{\n{prints}}}\n"));
    // positive
    vendored("shapes", "", &[("src/lib.rs", format!("{HEAD}{SHAPES}"))]);
    put("vendor/reg_util/Cargo.toml", &package("reg_util", "", false));
    put("vendor/reg_util/.cargo-checksum.json", "{\"files\":{},\"package\":null}");
    put("vendor/reg_util/src/lib.rs", "pub fn answer(words: usize) -> usize {\n    words * 6 + 7\n}\n");
    put("path_confined/Cargo.toml", &package("path_confined", "reg_util = \"0.1.0\"\n", true));
    put("path_confined/src/lib.rs", &format!("{HEAD}#[proc_macro]\npub fn via_registry(input: TokenStream) -> TokenStream {{\n    format!(\"pub const VIA_REGISTRY: usize = {{}};\", reg_util::answer(input.to_string().split_whitespace().count())).parse().unwrap()\n}}\n"));
    put("path_reads/Cargo.toml", &package("path_reads", "", true));
    put("path_reads/data.txt", "read from the workspace");
    put("path_reads/src/lib.rs", &format!("{HEAD}#[proc_macro]\npub fn read_data(_: TokenStream) -> TokenStream {{\n    let text = std::fs::read_to_string(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/data.txt\")).unwrap();\n    format!(\"pub const READ: &str = {{:?}};\", text).parse().unwrap()\n}}\n"));
    put("positive/Cargo.toml", &package("positive", "shapes = \"0.1.0\"\npath_confined = { path = \"../path_confined\" }\npath_reads = { path = \"../path_reads\" }\n", false));
    put("positive/src/main.rs", "shapes::shapes!(alpha beta alpha gamma beta alpha);\npath_confined::via_registry!(one two three);\npath_reads::read_data!();\nfn main() {\n    println!(\"{}\", SHAPES);\n    println!(\"via registry {}\", VIA_REGISTRY);\n    println!(\"{}\", READ);\n}\n");
    ws
}

/// A macro in the shapes of the ecosystem's base crates (proc-macro2, syn, quote, serde_derive).
const SHAPES: &str = r#"use std::cell::RefCell;
use std::collections::HashMap;
use std::sync::OnceLock;

thread_local! {
    static INTERNER: RefCell<HashMap<String, u32>> = RefCell::new(HashMap::new());
}
static SQUARES: OnceLock<Vec<u32>> = OnceLock::new();

/// A byte buffer on a raw allocation, as an arena or a small-string type keeps one.
struct Buf {
    p: *mut u8,
    len: usize,
    cap: usize,
}
impl Buf {
    fn new(cap: usize) -> Buf {
        let p = unsafe { std::alloc::alloc(std::alloc::Layout::array::<u8>(cap).unwrap()) };
        Buf { p, len: 0, cap }
    }
    fn push(&mut self, b: u8) {
        if self.len == self.cap {
            let p = unsafe { std::alloc::realloc(self.p, std::alloc::Layout::array::<u8>(self.cap).unwrap(), self.cap * 2) };
            self.p = p;
            self.cap *= 2;
        }
        unsafe { *self.p.add(self.len) = b };
        self.len += 1;
    }
    fn sum(&self) -> u32 {
        unsafe { std::slice::from_raw_parts(self.p, self.len) }.iter().map(|&b| b as u32).sum()
    }
}
impl Drop for Buf {
    fn drop(&mut self) {
        unsafe { std::alloc::dealloc(self.p, std::alloc::Layout::array::<u8>(self.cap).unwrap()) };
    }
}

#[proc_macro]
pub fn shapes(input: TokenStream) -> TokenStream {
    let _me = std::thread::current().id();
    let words: Vec<String> = input.to_string().split_whitespace().map(String::from).collect();
    let ids: Vec<u32> = words
        .iter()
        .map(|w| INTERNER.with(|m| {
            let mut m = m.borrow_mut();
            let next = m.len() as u32;
            *m.entry(w.clone()).or_insert(next)
        }))
        .collect();
    let squares = SQUARES.get_or_init(|| (0..16).map(|i| i * i).collect());
    let mut buf = Buf::new(4);
    for w in &words {
        for b in w.bytes() {
            buf.push(b);
        }
    }
    let caught = std::panic::catch_unwind(|| {
        if words.len() > 1 {
            panic!("caught inside the macro");
        }
    })
    .is_err();
    let dir = std::env::var("CARGO_MANIFEST_DIR").map_or(false, |d| d.ends_with("positive"));
    let text = format!("ids {:?} square {} bytes {} sum {} caught {} pkg {} dir {}", ids, squares[5], buf.len, buf.sum(), caught, env!("CARGO_PKG_NAME"), dir);
    let parsed: TokenStream = format!("pub const SHAPES: &str = {:?};", text).parse().unwrap();
    parsed
}
"#;
