//! The knob presets as data: the bench's eleven materials and two of ours
//! (Neumorphic dark, from the Knob cost explorer, and Showroom chrome), and
//! eighteen of its styles, which multiply -- any style in any material.
//!
//! A material carries the light, the finish, the surface (metal, clear coat,
//! the studio it reflects) and the inks; a style carries the geometry: the
//! revolve profile, the grip, the wing, the cut and the marks. Both are the
//! numbers the Material Bench (`material-bench-v74.html`) hands its shader
//! after its own preprocessing, so a knob drawn here from the same pair reads
//! as the bench's.
//!
//! A style is a const with borrowed curves; [`KnobShape`] is the same
//! geometry owned, for a knob whose shape is being edited.
use std::sync::OnceLock;

/// One material: light, finish, surface, shadow and inks.
///
/// The fields are the bench's keys. Inks are `0xRRGGBBAA`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct KnobMaterial {
    pub name: &'static str,
    /// Tier: 0 flat, 1 relief, 2 rim, gloss and specular as well.
    pub level: f64,
    /// The key light, x right, y down, z toward the viewer.
    pub lx: f64,
    pub ly: f64,
    pub lz: f64,
    /// Its intensity.
    pub li: f64,
    /// Bevel width and curve of a flat face (a well's).
    pub bw: f64,
    pub bc: f64,
    /// How far a face stands off the ground, and how deep a well goes.
    pub raise: f64,
    pub sink: f64,
    pub spec: f64,
    pub rough: f64,
    pub ao: f64,
    pub rim: f64,
    pub gloss: f64,
    pub glow: f64,
    /// Cast shadow strength, blur, falloff (linear to exponential) and the
    /// contact occlusion.
    pub shadow: f64,
    pub sblur: f64,
    pub fall: f64,
    pub oao: f64,
    /// A well's inner shadow and its blur.
    pub inner: f64,
    pub inner_r: f64,
    /// The light-side lip a raised part throws on its ground.
    pub lip: f64,
    pub facegrad: f64,
    pub hair: f64,
    pub aoreach: f64,
    /// The knob's height in radii, and the crease blur its profile is baked
    /// with.
    pub pdepth: f64,
    pub psmooth: f64,
    /// Mark finish: 0 paint, 1 engrave, 2 emboss, 3 LED; and the bevel or
    /// LED housing.
    pub pfin: f64,
    pub mbev: f64,
    /// Reflection strength, metallic, exposure (EV), highlight roll-off,
    /// clear coat and its roughness, the studio (0 studio, 1 chrome studio,
    /// 2 outdoor) and the reflection's perspective.
    pub env: f64,
    pub metal: f64,
    pub ev: f64,
    pub roll: f64,
    pub coat: f64,
    pub coatr: f64,
    pub envk: f64,
    pub persp: f64,
    /// How many strip lights hang round the chrome studio's walls: the
    /// first a turn over `lights + 1` round from the key light, the rest
    /// evenly after it, so the bench's three stand at right angles. Past
    /// three, every other one hangs high and short.
    pub lights: f64,
    /// How many panes the chrome studio's ceiling panel is glazed in: one
    /// is the bench's plain panel, more put a window in a flat face.
    pub panes: f64,
    pub ground: u32,
    pub body_ink: u32,
    pub light_ink: u32,
    pub shadow_ink: u32,
    pub glow_ink: u32,
    pub ptr_ink: u32,
}

/// A curve anchor: `[x, y, type]`, type 0 point, 1 smooth, 2 corner,
/// 3 horizontal.
pub type Anchor = [f64; 3];

/// One knob style: the geometry. The field names are the bench's keys.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct KnobStyle {
    pub name: &'static str,
    /// A cap inset in the top, its radius (0 none) and its ink, and how
    /// much of a spun-metal finish it takes.
    pub capr: f64,
    pub cap_ink: u32,
    pub spun: f64,
    /// A flat cut across the side at this fraction of the radius (0 none).
    pub flat: f64,
    /// The wing: root and tip along the pointer in radii, width, fillet,
    /// end rounding, and its curves: width along it, crest height along it,
    /// and the section across it. Mode 0 adds a ridge, 1 takes two cutters
    /// away; the base is the level the section stands on.
    pub wr0: f64,
    pub wr1: f64,
    pub wwmax: f64,
    pub barfil: f64,
    pub wendr: f64,
    pub wmode: f64,
    pub wbase: f64,
    pub wwid: &'static [Anchor],
    pub whgt: &'static [Anchor],
    pub wprof: &'static [Anchor],
    /// The value arc: radius, width, and the well it runs in.
    pub arcr: f64,
    pub arcw: f64,
    pub awell: f64,
    /// A well the knob stands in, in radii (0 none).
    pub well: f64,
    /// Dial ticks: count, radius, length, stroke.
    pub ticks: f64,
    pub tickr: f64,
    pub tickl: f64,
    pub tickw: f64,
    /// The revolve profile, centre (x 0) to rim (x 1).
    pub prof: &'static [Anchor],
    /// The grip: columns, tooth depth, sharpness, taper across its band,
    /// the band (the profile anchors it runs between) and the tooth curve.
    pub flutes: f64,
    pub fd: f64,
    pub fs: f64,
    pub gtaper: f64,
    pub ffrom: usize,
    pub fto: usize,
    pub flute: &'static [Anchor],
    /// The pointer: 0 none, 1 line, 2 tapered, 3 dot; inner and outer
    /// radius; width.
    pub ptype: f64,
    pub pr0: f64,
    pub pr1: f64,
    pub pw: f64,
    /// The cut: 0 none, 1 dimple, 2 slot, 3 scallops, 4 ring; count,
    /// position, size, half length, floor, wall, fillet; a spherical dimple
    /// and its centre height.
    pub cut: f64,
    pub cn: f64,
    pub cr: f64,
    pub cs: f64,
    pub cl: f64,
    pub cf: f64,
    pub cw: f64,
    pub cfil: f64,
    pub csph: f64,
    pub cz: f64,
}

impl KnobStyle {
    /// The name the gallery shows.
    pub fn label(&self) -> String {
        let mut chars = self.name.chars();
        match chars.next() {
            Some(first) => first.to_uppercase().chain(chars).collect(),
            None => String::new(),
        }
    }
}

