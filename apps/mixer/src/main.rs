app_main!(App);

/// Posted by the client thread whenever new events are queued.
#[derive(Debug)]
struct NetPing;

const LAYOUTS: &[(&str, &str)] = &[("LR MIX", "lr_mix"), ("COMPACT", "compact")];

/// Reconcile passes after the initial sweep, and how far apart they sit.
const RESWEEP_ROUNDS: u32 = 8;
const RESWEEP_EVERY: std::time::Duration = std::time::Duration::from_millis(1200);

fn load_layout_body(name: &str) -> String {
    let candidates = [
        format!("apps/mixer/layouts/{name}.splash"),
        format!("{}/layouts/{name}.splash", env!("CARGO_MANIFEST_DIR")),
    ];
    for c in &candidates {
        if let Ok(s) = std::fs::read_to_string(c) {
            return s;
        }
    }
    match name {
        "lr_mix" => include_str!("../layouts/lr_mix.splash").to_string(),
        "compact" => include_str!("../layouts/compact.splash").to_string(),
        _ => String::new(),
    }
}

