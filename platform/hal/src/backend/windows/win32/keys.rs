//! Virtual keys to the shared key-code table. Moved from os/windows/win32_window.rs
//! (`virtual_key_to_key_code`); the numeric VK values are Win32's (WinUser.h).

use makepad_key_code::KeyCode;

/// The key of a virtual-key code; `extended` (lParam bit 24) tells numpad Enter from Return.
pub fn key_code(vk: u16, extended: bool) -> KeyCode {
    match vk {
        0x1B => KeyCode::Escape,
        0xC0 => KeyCode::Backtick,
        0x30 => KeyCode::Key0,
        0x31 => KeyCode::Key1,
        0x32 => KeyCode::Key2,
        0x33 => KeyCode::Key3,
        0x34 => KeyCode::Key4,
        0x35 => KeyCode::Key5,
        0x36 => KeyCode::Key6,
        0x37 => KeyCode::Key7,
        0x38 => KeyCode::Key8,
        0x39 => KeyCode::Key9,
        0xBD => KeyCode::Minus,
        0xBB => KeyCode::Equals,
        0x08 => KeyCode::Backspace,
        0x09 => KeyCode::Tab,
        0x51 => KeyCode::KeyQ,
        0x57 => KeyCode::KeyW,
        0x45 => KeyCode::KeyE,
        0x52 => KeyCode::KeyR,
        0x54 => KeyCode::KeyT,
        0x59 => KeyCode::KeyY,
        0x55 => KeyCode::KeyU,
        0x49 => KeyCode::KeyI,
        0x4F => KeyCode::KeyO,
        0x50 => KeyCode::KeyP,
        0xDB => KeyCode::LBracket,
        0xDD => KeyCode::RBracket,
        0x0D if extended => KeyCode::NumpadEnter,
        0x0D => KeyCode::ReturnKey,
        0x41 => KeyCode::KeyA,
        0x53 => KeyCode::KeyS,
        0x44 => KeyCode::KeyD,
        0x46 => KeyCode::KeyF,
        0x47 => KeyCode::KeyG,
        0x48 => KeyCode::KeyH,
        0x4A => KeyCode::KeyJ,
        0x4B => KeyCode::KeyK,
        0x4C => KeyCode::KeyL,
        0xBA => KeyCode::Semicolon,
        0xDE => KeyCode::Quote,
        0xDC => KeyCode::Backslash,
        0x5A => KeyCode::KeyZ,
        0x58 => KeyCode::KeyX,
        0x43 => KeyCode::KeyC,
        0x56 => KeyCode::KeyV,
        0x42 => KeyCode::KeyB,
        0x4E => KeyCode::KeyN,
        0x4D => KeyCode::KeyM,
        0xBC => KeyCode::Comma,
        0xBE => KeyCode::Period,
        0xBF => KeyCode::Slash,
        0x11 | 0xA2 | 0xA3 => KeyCode::Control,
        0x12 | 0xA4 | 0xA5 => KeyCode::Alt,
        0x10 | 0xA0 | 0xA1 => KeyCode::Shift,
        0x5B | 0x5C => KeyCode::Logo,
        0x20 => KeyCode::Space,
        0x14 => KeyCode::Capslock,
        0x70 => KeyCode::F1,
        0x71 => KeyCode::F2,
        0x72 => KeyCode::F3,
        0x73 => KeyCode::F4,
        0x74 => KeyCode::F5,
        0x75 => KeyCode::F6,
        0x76 => KeyCode::F7,
        0x77 => KeyCode::F8,
        0x78 => KeyCode::F9,
        0x79 => KeyCode::F10,
        0x7A => KeyCode::F11,
        0x7B => KeyCode::F12,
        0x2C => KeyCode::PrintScreen,
        0x91 => KeyCode::ScrollLock,
        0x13 => KeyCode::Pause,
        0x2D => KeyCode::Insert,
        0x2E => KeyCode::Delete,
        0x24 => KeyCode::Home,
        0x23 => KeyCode::End,
        0x21 => KeyCode::PageUp,
        0x22 => KeyCode::PageDown,
        0x60 => KeyCode::Numpad0,
        0x61 => KeyCode::Numpad1,
        0x62 => KeyCode::Numpad2,
        0x63 => KeyCode::Numpad3,
        0x64 => KeyCode::Numpad4,
        0x65 => KeyCode::Numpad5,
        0x66 => KeyCode::Numpad6,
        0x67 => KeyCode::Numpad7,
        0x68 => KeyCode::Numpad8,
        0x69 => KeyCode::Numpad9,
        0x6D => KeyCode::NumpadSubtract,
        0x6B => KeyCode::NumpadAdd,
        0x6E => KeyCode::NumpadDecimal,
        0x6A => KeyCode::NumpadMultiply,
        0x6F => KeyCode::NumpadDivide,
        0x90 => KeyCode::Numlock,
        0x26 => KeyCode::ArrowUp,
        0x28 => KeyCode::ArrowDown,
        0x25 => KeyCode::ArrowLeft,
        0x27 => KeyCode::ArrowRight,
        _ => KeyCode::Unknown,
    }
}
