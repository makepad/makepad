/// Synthesis window D, in f32.
pub fn synth_window() -> [f32; 512] {
    let mut out = [0.0f32; 512];
    for (o, &q) in out.iter_mut().zip(SYNTH_WINDOW_Q16.iter()) {
        *o = q as f32 / 65536.0;
    }
    out
}

