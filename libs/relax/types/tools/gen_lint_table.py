#!/usr/bin/env python3
"""Generates libs/relax/types/src/lint_table.rs from the rustc sources (rustc 1.97.1 compiler/):
every built-in lint's name, default level, edition-dependent level, lint groups, whether an
unstable feature gates it, and the renamed / removed lint names.

usage: gen_lint_table.py <rust-src>/compiler > libs/relax/types/src/lint_table.rs
"""
import os, re, sys

root = sys.argv[1]
lints = {}  # name -> dict

def strip_docs(text):
    # doc comments and `#[doc = "..."]` attributes (their strings may hold unbalanced braces)
    text = re.sub(r'#\[doc\s*=\s*"(?:[^"\\]|\\.)*"\]', "", text)
    return "\n".join(l for l in text.splitlines() if not l.strip().startswith("//"))

def parse_blocks(text, path):
    text = strip_docs(text)
    for m in re.finditer(r"declare_lint!\s*\{", text):
        i = m.end()
        depth = 1
        j = i
        while depth and j < len(text):
            c = text[j]
            if c == "{": depth += 1
            elif c == "}": depth -= 1
            j += 1
        body = text[i:j - 1]
        h = re.match(r"\s*(?:#\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?([A-Z][A-Z0-9_]*)\s*,\s*(Allow|Warn|Deny|Forbid)\s*,", body)
        if not h:
            continue
        name, level = h.group(1).lower(), h.group(2)
        info = {"level": level, "level2024": None, "groups": [], "gated": False}
        e = re.search(r"@edition\s+Edition(\d+)\s*=>\s*(Allow|Warn|Deny|Forbid)", body)
        if e: info["level2024"] = (int(e.group(1)), e.group(2))
        if "@feature_gate" in body: info["gated"] = True
        if "@future_incompatible" in body:
            r = re.search(r"reason:\s*fcw!\(\s*(EditionError|EditionSemanticsChange)\s+(\d+)", body)
            if r: info["groups"].append("rust_%s_compatibility" % r.group(2))
            else: info["groups"].append("future_incompatible")
        lints[name] = info

for dp, dn, fn in os.walk(root):
    if "/tests" in dp or "/target" in dp: continue
    for f in fn:
        if f.endswith(".rs"):
            p = os.path.join(dp, f)
            t = open(p, errors="replace").read()
            if "declare_lint!" in t:
                parse_blocks(t, p)

lib = open(os.path.join(root, "rustc_lint/src/lib.rs"), errors="replace").read()
# add_lint_group!("name", A, B, ...)
for m in re.finditer(r'add_lint_group!\(\s*"([a-z_0-9]+)"\s*,(.*?)\);', lib, re.S):
    members = re.findall(r"\b([A-Z][A-Z0-9_]+)\b", re.sub(r"//[^\n]*", "", m.group(2)))
    for mem in members:
        n = mem.lower()
        if n in lints and m.group(1) not in lints[n]["groups"]:
            lints[n]["groups"].append(m.group(1))
renamed = re.findall(r'register_renamed\(\s*"([a-z_0-9]+)"\s*,\s*"([a-z_0-9]+)"\s*\)', lib)
removed = []
for m in re.finditer(r'register_removed\(\s*"([a-z_0-9]+)"\s*,\s*("(?:[^"\\]|\\.)*"(?:\s*\n\s*"(?:[^"\\]|\\.)*")*)\s*,?\s*\)', lib):
    msg = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2)))
    msg = re.sub(r"\\\n\s*", "", msg)
    removed.append((m.group(1), msg))
ignored = re.findall(r'"([a-z_]+)",?\n', lib[lib.index("RUSTDOC_LINTS"):lib.index("RUSTDOC_LINTS") + 400])

# rustc's late lints (rustc_interface passes.rs analysis, misc_checking_3, after the required analyses):
# the lints of the passes of rustc_lint's BuiltinCombinedModuleLateLintPass, clashing_extern_declarations,
# and what misc_checking_3's other checks report (rustc_passes dead.rs, rustc_privacy private-in-public,
# check_expectations)
i = lib.index("BuiltinCombinedModuleLateLintPass,")
late_passes = re.findall(r"^\s*([A-Z][A-Za-z0-9]*)\s*:", lib[i:lib.index("]", lib.index("[", i))], re.M)
pass_lints = {}
for dp, dn, fn in os.walk(os.path.join(root, "rustc_lint/src")):
    for f in fn:
        if not f.endswith(".rs"): continue
        t = strip_docs(open(os.path.join(dp, f), errors="replace").read())
        for m in re.finditer(r"(?:declare|impl)_lint_pass!\s*\(\s*(?:pub\s+)?([A-Z][A-Za-z0-9]*)(?:\s*<[^>]*>)?\s*=>\s*\[([^\]]*)\]", t):
            pass_lints.setdefault(m.group(1), set()).update(x.lower() for x in re.findall(r"\b([A-Z][A-Z0-9_]+)\b", m.group(2)))
missing = [p for p in late_passes if p not in pass_lints]
if missing: sys.exit("late lint passes without a lint list: %s" % missing)
late = {l for p in late_passes for l in pass_lints[p]}
late |= {"clashing_extern_declarations", "dead_code", "dead_code_pub_in_binary", "private_interfaces", "private_bounds", "unnameable_types", "unfulfilled_lint_expectations"}

def lv(x): return "L" + x[0]
print("// Generated by tools/gen_lint_table.py from the rustc sources; do not edit by hand.")
print("//! The built-in lints of rustc 1.97.1: name, default level, groups; renamed and removed names.")
print()
print("#[derive(Clone, Copy, PartialEq, Eq)]")
print("pub enum LevelK { Allow, Warn, Deny, Forbid }")
print("use LevelK::*;")
print()
print("/// (name, default level, (edition, level from it), groups, gated by an unstable feature)")
print("pub const LINTS: &[(&str, LevelK, Option<(u16, LevelK)>, &[&str], bool)] = &[")
for n in sorted(lints):
    i = lints[n]
    l2 = "None" if not i["level2024"] else "Some((%d, %s))" % (i["level2024"][0], i["level2024"][1])
    gs = ", ".join('"%s"' % g for g in i["groups"])
    print('    ("%s", %s, %s, &[%s], %s),' % (n, i["level"], l2, gs, "true" if i["gated"] else "false"))
print("];")
print()
print("pub static RENAMED: &[(&str, &str)] = &[")
for a, b in renamed: print('    ("%s", "%s"),' % (a, b))
print("];")
print()
print("pub static REMOVED: &[(&str, &str)] = &[")
for a, b in removed: print('    ("%s", "%s"),' % (a, b.replace('"', '\\"')))
print("];")
print()
print("/// rustc's late lints, sorted: its late lint pass's and misc_checking_3's (rustc_interface passes.rs")
print("/// analysis), which a compilation whose required analyses failed never reaches.")
print("pub static LATE: &[&str] = &[")
for n in sorted(late & set(lints)): print('    "%s",' % n)
print("];")
print()
print("/// Lint group names (besides `warnings`).")
groups = sorted({g for i in lints.values() for g in i["groups"]} | {"nonstandard_style", "unused", "future_incompatible", "let_underscore", "keyword_idents", "refining_impl_trait", "deprecated_safe", "unknown_or_malformed_diagnostic_attributes", "rust_2018_idioms"})
print("pub static GROUPS: &[&str] = &[" + ", ".join('"%s"' % g for g in groups) + ", \"bad_style\", \"warnings\"];")
