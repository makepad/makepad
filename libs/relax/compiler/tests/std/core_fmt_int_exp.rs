// LowerExp and UpperExp for the integer types (stable since 1.42): `{:e}` / `{:E}` print an integer
// as a coefficient in [1, 10) and a power of ten. The std here had them for f32 and f64 only, so
// wide 0.7's formatter impls for its integer vectors (src/lib.rs, `impl_formatter_for!`:
// `LowerExp::fmt(a_ref, f)` over the lanes of an i16x8) failed with "the trait bound `i16:
// LowerExp` is not satisfied". The expected strings are rustc's.
use std::fmt::{self, LowerExp, UpperExp};

macro_rules! c {
    ($fmt:literal, $v:expr, $want:literal) => {
        assert_eq!(format!($fmt, $v), $want, "{} of {}", $fmt, stringify!($v));
    };
}

// wide's shape: a vector type that formats each lane through the lane type's own impl
struct I16x8([i16; 8]);
struct U64x2([u64; 2]);
macro_rules! lanes {
    ($($tr:ident for $t:ty),+) => {
        $(impl $tr for $t {
            fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
                write!(f, "(")?;
                for (x, a_ref) in self.0.iter().enumerate() {
                    if x > 0 {
                        write!(f, ", ")?;
                    }
                    $tr::fmt(a_ref, f)?;
                }
                write!(f, ")")
            }
        })+
    };
}
lanes!(LowerExp for I16x8, UpperExp for I16x8, LowerExp for U64x2, UpperExp for U64x2);

fn exp_of<T: LowerExp + UpperExp>(t: T) -> (String, String) {
    (format!("{:e}", t), format!("{:E}", t))
}

#[test]
fn a01_every_integer_type_shortest() {
    c!("{:e}", 0u8, "0e0");
    c!("{:e}", 1u8, "1e0");
    c!("{:e}", 7i8, "7e0");
    c!("{:e}", 10u8, "1e1");
    c!("{:e}", 100u8, "1e2");
    c!("{:e}", 255u8, "2.55e2");
    c!("{:e}", -128i8, "-1.28e2");
    c!("{:e}", 127i8, "1.27e2");
    c!("{:e}", 1234i16, "1.234e3");
    c!("{:e}", -1200i16, "-1.2e3");
    c!("{:e}", 32767i16, "3.2767e4");
    c!("{:e}", -32768i16, "-3.2768e4");
    c!("{:e}", 65535u16, "6.5535e4");
    c!("{:e}", 100000u32, "1e5");
    c!("{:e}", 123456789i32, "1.23456789e8");
    c!("{:e}", -2147483648i32, "-2.147483648e9");
    c!("{:e}", 4294967295u32, "4.294967295e9");
    c!("{:e}", 9223372036854775807i64, "9.223372036854775807e18");
    c!("{:e}", -9223372036854775808i64, "-9.223372036854775808e18");
    c!("{:e}", 18446744073709551615u64, "1.8446744073709551615e19");
    c!("{:e}", 1000000000000000000u64, "1e18");
    c!("{:e}", 12345usize, "1.2345e4");
    c!("{:e}", -12345isize, "-1.2345e4");
    c!("{:e}", 340282366920938463463374607431768211455u128, "3.40282366920938463463374607431768211455e38");
    c!("{:e}", -170141183460469231731687303715884105728i128, "-1.70141183460469231731687303715884105728e38");
    c!("{:e}", 100000000000000000000000000000000000000u128, "1e38");
    c!("{:e}", 0i128, "0e0");
    c!("{:E}", 0i16, "0E0");
    c!("{:E}", 1234i16, "1.234E3");
    c!("{:E}", -1200i16, "-1.2E3");
    c!("{:E}", 255u8, "2.55E2");
    c!("{:E}", -128i8, "-1.28E2");
    c!("{:E}", 18446744073709551615u64, "1.8446744073709551615E19");
    c!("{:E}", -9223372036854775808i64, "-9.223372036854775808E18");
    c!("{:E}", 340282366920938463463374607431768211455u128, "3.40282366920938463463374607431768211455E38");
    c!("{:E}", 5usize, "5E0");
    // through a generic bound and through references
    assert_eq!(exp_of(4096u16), ("4.096e3".to_string(), "4.096E3".to_string()));
    assert_eq!(exp_of(&-4096i64), ("-4.096e3".to_string(), "-4.096E3".to_string()));
    assert_eq!(exp_of(&mut 70usize), ("7e1".to_string(), "7E1".to_string()));
}

