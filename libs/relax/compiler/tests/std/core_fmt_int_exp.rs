#[test]
fn a04_lanes_of_a_vector() {
    let v = I16x8([0, 1, -1, 10, 1234, -1200, i16::MAX, i16::MIN]);
    assert_eq!(format!("{:e}", v), "(0e0, 1e0, -1e0, 1e1, 1.234e3, -1.2e3, 3.2767e4, -3.2768e4)");
    assert_eq!(format!("{:E}", v), "(0E0, 1E0, -1E0, 1E1, 1.234E3, -1.2E3, 3.2767E4, -3.2768E4)");
    assert_eq!(format!("{:.1e}", v), "(0.0e0, 1.0e0, -1.0e0, 1.0e1, 1.2e3, -1.2e3, 3.3e4, -3.3e4)");
    let w = U64x2([u64::MAX, 600]);
    assert_eq!(format!("{:e}", w), "(1.8446744073709551615e19, 6e2)");
    assert_eq!(format!("{:+08.2E}", w), "(+1.84E19, +06.00E2)");
}
