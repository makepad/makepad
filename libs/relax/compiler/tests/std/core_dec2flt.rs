// Float parsing differential observations: both widths, including exact fallback cases.
fn observe(s: &str) {
    match s.parse::<f64>() {
        Ok(v) => println!("| f64 {}", v.to_bits()),
        Err(e) => println!("| f64 error {}", e),
    }
    match s.parse::<f32>() {
        Ok(v) => println!("| f32 {}", v.to_bits()),
        Err(e) => println!("| f32 error {}", e),
    }
}

