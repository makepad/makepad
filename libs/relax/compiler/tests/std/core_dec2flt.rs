#[test]
fn a02_decimal_cases() {
    let mut state = 0x81e94d72c35ab60fu64;
    let mut i = 0;
    while i < 320 {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        let exponent = (state % 720) as i32 - 370;
        let s = format!("{}e{}", state, exponent);
        observe(&s);
        i += 1;
    }
}

#[test]
fn a03_long_midpoints() {
    let mut s = String::from("1.00000000000000011102230246251565404236316680908203125");
    let mut i = 0;
    while i < 800 { s.push('0'); i += 1; }
    observe(&s);
    s.push('1');
    observe(&s);
    let mut s = String::from("1.000000059604644775390625");
    let mut i = 0;
    while i < 800 { s.push('0'); i += 1; }
    observe(&s);
    s.push('1');
    observe(&s);
}

