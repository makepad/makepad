fn apply(f: fn(u32) -> Big, x: u32) -> Big {
    f(x)
}

/// The variant's index and field, read from the value itself.
fn read(value: &Big) -> (u32, u32) {
    // SAFETY: a fieldless-tag enum of 300 one-field variants is a u16 tag and a u32
    let tag = unsafe { *(value as *const Big as *const u16) };
    let field = match value {
        Big::V0(x) | Big::V238(x) | Big::V239(x) | Big::V240(x) | Big::V244(x) | Big::V255(x) | Big::V256(x) | Big::V299(x) => *x,
        _ => u32::MAX,
    };
    (tag as u32, field)
}

#[test]
fn a_constructor_of_a_late_variant_is_a_function_value() {
    // through `Result::map`, as stylo's generated `parse_declared` does
    let parsed: Result<u32, ()> = Ok(7);
    assert!(matches!(parsed.map(Big::V255), Ok(Big::V255(7))));
    assert!(matches!(Some(3).map(Big::V239), Some(Big::V239(3))));
    assert!(matches!(Some(3).map(Big::V240), Some(Big::V240(3))));
    assert!(matches!(Some(4).map(Big::V299), Some(Big::V299(4))));
    // as plain fn pointers: every one builds its own variant
    let ctors: [(fn(u32) -> Big, u32); 8] = [
        (Big::V0, 0), (Big::V238, 238), (Big::V239, 239), (Big::V240, 240),
        (Big::V244, 244), (Big::V255, 255), (Big::V256, 256), (Big::V299, 299),
    ];
    for (ctor, index) in ctors {
        assert_eq!(read(&apply(ctor, index + 1000)), (index, index + 1000));
    }
}
