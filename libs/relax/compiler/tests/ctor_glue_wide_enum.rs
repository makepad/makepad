fn apply(f: fn(u32) -> Wide, x: u32) -> Wide {
    f(x)
}

fn tag(v: &Wide) -> u16 {
    match v {
        Wide::V0(_) => 0,
        Wide::V239(_) => 239,
        Wide::V240(_) => 240,
        Wide::V246(_) => 246,
        _ => u16::MAX,
    }
}

fn payload(v: &Wide) -> u32 {
    match v {
        Wide::V0(x) => *x,
        Wide::V239(x) => *x,
        Wide::V240(x) => *x,
        Wide::V246(x) => *x,
        _ => u32::MAX,
    }
}

#[test]
fn constructor_fn_past_u8_glue_kind_keeps_its_variant() {
    let cases: [(fn(u32) -> Wide, u16); 4] = [
        (Wide::V0, 0),
        (Wide::V239, 239),
        (Wide::V240, 240),
        (Wide::V246, 246),
    ];
    for (ctor, index) in cases {
        let v = apply(ctor, 7);
        assert_eq!(tag(&v), index, "constructor fn built the wrong variant");
        assert_eq!(payload(&v), 7, "constructor fn wrote the wrong payload");
        drop(v);
    }
}
