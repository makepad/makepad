# Writes arrays.rs: `unsafe impl<T> Array for [T; N]` for smallvec 1.x's size list.
sizes = list(range(0, 33)) + [36, 0x40, 0x60, 0x80, 0x100, 0x200, 0x400, 0x600, 0x800, 0x1000, 0x2000,
         0x4000, 0x6000, 0x8000, 0x10000, 0x20000, 0x40000, 0x60000, 0x80000, 0x100000]
out = ["// GENERATED by libs/relax/compiler/std/smallvec/gen_arrays.py: `Array` for the array sizes smallvec 1.x",
       "// implements without its const_generics feature (Relax has no macro_rules; edit the script).",
       "", "use super::Array;", ""]
for n in sizes:
    out.append("unsafe impl<T> Array for [T; %d] {\n    type Item = T;\n    fn size() -> usize {\n        %d\n    }\n}" % (n, n))
open(__file__.replace("gen_arrays.py", "arrays.rs"), "w").write("\n".join(out) + "\n")
