//! Generates core/tuple.rs: Default, PartialEq, Eq, PartialOrd, Ord and Debug for
//! tuples of 1..=12 elements (Hash is in hash/mod.rs). Lexicographic like real core.

use std::fmt::Write;

pub fn run(core: &str) {
    let mut o = String::new();
    o.push_str("// GENERATED by libs/relax/compiler/std/check/src/gen_tuple.rs (`relax-std-gen tuple ../core`).\n");
    o.push_str("// Do not edit by hand: change the generator and re-run it.\n");
    o.push_str("//! Trait impls for tuples (Relax only).\n\n");
    o.push_str("use crate::cmp::Ordering;\nuse crate::fmt;\n\n");
    let names = ["A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "L"];
    for n in 1..=12usize {
        let ts = &names[..n];
        let tys = ts.join(", ");
        let tup = if n == 1 { format!("({},)", tys) } else { format!("({})", tys) };
        let bound = |b: &str| ts.iter().map(|t| format!("{t}: {b}")).collect::<Vec<_>>().join(", ");
        let idx: Vec<String> = (0..n).map(|i| i.to_string()).collect();
        let _ = writeln!(o, "impl<{}> Default for {tup} {{ fn default() -> {tup} {{ ({}{}) }} }}", bound("Default"), ts.iter().map(|t| format!("{t}::default()")).collect::<Vec<_>>().join(", "), if n == 1 { "," } else { "" });
        let _ = writeln!(o, "impl<{}> PartialEq for {tup} {{ fn eq(&self, other: &{tup}) -> bool {{ {} }} }}", bound("PartialEq"), idx.iter().map(|i| format!("self.{i} == other.{i}")).collect::<Vec<_>>().join(" && "));
        let _ = writeln!(o, "impl<{}> Eq for {tup} {{}}", bound("Eq"));
        // partial_cmp: first non-equal element decides
        let mut pc = String::new();
        for (k, i) in idx.iter().enumerate() {
            if k + 1 == n {
                let _ = write!(pc, "self.{i}.partial_cmp(&other.{i})");
            } else {
                let _ = write!(pc, "match self.{i}.partial_cmp(&other.{i}) {{ Some(Ordering::Equal) => {{}} c => return c }} ");
            }
        }
        let _ = writeln!(o, "impl<{}> PartialOrd for {tup} {{ fn partial_cmp(&self, other: &{tup}) -> Option<Ordering> {{ {pc} }} }}", bound("PartialOrd"));
        let mut c = String::new();
        for (k, i) in idx.iter().enumerate() {
            if k + 1 == n {
                let _ = write!(c, "self.{i}.cmp(&other.{i})");
            } else {
                let _ = write!(c, "match self.{i}.cmp(&other.{i}) {{ Ordering::Equal => {{}} c => return c }} ");
            }
        }
        let _ = writeln!(o, "impl<{}> Ord for {tup} {{ fn cmp(&self, other: &{tup}) -> Ordering {{ {c} }} }}", bound("Ord"));
        let _ = writeln!(
            o,
            "impl<{}> fmt::Debug for {tup} {{ fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{ let mut b = f.debug_tuple(\"\"); {} b.finish() }} }}",
            bound("fmt::Debug"),
            idx.iter().map(|i| format!("b.field(&self.{i});")).collect::<Vec<_>>().join(" ")
        );
        o.push('\n');
    }
    std::fs::write(format!("{}/tuple.rs", core), o).expect("write tuple.rs");

    // fn pointers: Debug and Pointer print the address, for every fn pointer through the builtin
    // FnPtr trait as real core does (library/core/src/ptr/mod.rs `impl<F: FnPtr> fmt::Debug for F`):
    // per-arity impls (`impl<Ret, A> Debug for fn(A) -> Ret`) never match a higher-ranked fn
    // pointer such as `for<'a> fn(&'a mut T)`, whose binder no impl argument can name.
    let mut f = String::new();
    f.push_str("// GENERATED by libs/relax/compiler/std/check/src/gen_tuple.rs (`relax-std-gen tuple ../core`).\n");
    f.push_str("// Do not edit by hand: change the generator and re-run it.\n");
    f.push_str("//! fmt::Debug and fmt::Pointer for fn pointers (Relax only): the address, like real core.\n\n");
    f.push_str("use crate::fmt;\nuse crate::ops::FnPtr;\n\n");
    for tr in ["Pointer", "Debug"] {
        let _ = writeln!(f, "impl<F: FnPtr> fmt::{tr} for F {{ fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{ fmt::Pointer::fmt(&(FnPtr::addr(*self) as *const ()), f) }} }}");
    }
    // library/core/src/ptr/mod.rs: comparison and hashing of fn pointers go by address
    f.push_str("use crate::cmp::{Ordering, PartialOrd, Ord};\nuse crate::hash::{Hash, Hasher};\n\n");
    f.push_str("impl<F: FnPtr> PartialEq for F { fn eq(&self, other: &Self) -> bool { self.addr() == other.addr() } }\n");
    f.push_str("impl<F: FnPtr> Eq for F {}\n");
    f.push_str("impl<F: FnPtr> PartialOrd for F { fn partial_cmp(&self, other: &Self) -> Option<Ordering> { self.addr().partial_cmp(&other.addr()) } }\n");
    f.push_str("impl<F: FnPtr> Ord for F { fn cmp(&self, other: &Self) -> Ordering { self.addr().cmp(&other.addr()) } }\n");
    f.push_str("impl<F: FnPtr> Hash for F { fn hash<HH: Hasher>(&self, state: &mut HH) { state.write_usize(self.addr()) } }\n");
    std::fs::write(format!("{}/fn_ptr.rs", core), f).expect("write fn_ptr.rs");
    eprintln!("gen_tuple: wrote tuple.rs");
}
