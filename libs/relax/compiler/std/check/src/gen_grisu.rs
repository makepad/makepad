//! Exact-integer port of real core's Grisu cached-power generator (MIT/Apache-2.0).
//! Base-2^32 arithmetic; no host floats or external dependencies.

use std::fmt::Write;

// Little-endian base-2^32 limbs; zero has no limbs.
struct Big {
    limbs: Vec<u32>,
}

impl Big {
    fn one() -> Self { Self { limbs: vec![1] } }
    fn bits(&self) -> usize {
        match self.limbs.last() {
            Some(v) => (self.limbs.len() - 1) * 32 + (32 - v.leading_zeros()) as usize,
            None => 0,
        }
    }
    fn mul_small(&mut self, m: u32) {
        let mut carry = 0u64;
        for x in &mut self.limbs {
            let v = *x as u64 * m as u64 + carry;
            *x = v as u32;
            carry = v >> 32;
        }
        if carry != 0 { self.limbs.push(carry as u32); }
    }
    fn add_one(&mut self) {
        for x in &mut self.limbs {
            let (v, carry) = x.overflowing_add(1);
            *x = v;
            if !carry { return; }
        }
        self.limbs.push(1);
    }
    fn ge(&self, other: &Self) -> bool {
        if self.limbs.len() != other.limbs.len() { return self.limbs.len() > other.limbs.len(); }
        for i in (0..self.limbs.len()).rev() {
            if self.limbs[i] != other.limbs[i] { return self.limbs[i] > other.limbs[i]; }
        }
        true
    }
    fn sub(&mut self, other: &Self) {
        let mut borrow = 0u64;
        for i in 0..self.limbs.len() {
            let rhs = other.limbs.get(i).copied().unwrap_or(0) as u64 + borrow;
            let lhs = self.limbs[i] as u64;
            self.limbs[i] = lhs.wrapping_sub(rhs) as u32;
            borrow = (lhs < rhs) as u64;
        }
        assert_eq!(borrow, 0);
        while self.limbs.last() == Some(&0) { self.limbs.pop(); }
    }
    // Binary long division of 2^exponent by divisor.
    fn divide_power_two(exponent: usize, divisor: &Self) -> Self {
        let mut remainder = Self { limbs: Vec::new() };
        let mut quotient = Self { limbs: vec![0; exponent / 32 + 1] };
        for bit in (0..=exponent).rev() {
            remainder.mul_small(2);
            if bit == exponent { remainder.add_one(); }
            if remainder.ge(divisor) {
                remainder.sub(divisor);
                quotient.limbs[bit / 32] |= 1 << (bit % 32);
            }
        }
        while quotient.limbs.last() == Some(&0) { quotient.limbs.pop(); }
        quotient
    }
    // Extract the leading 128 bits for exact 64-bit rounding below.
    fn normalized(&self) -> u128 {
        let bits = self.bits();
        let start = bits.saturating_sub(128);
        let mut value = 0u128;
        for bit in start..bits {
            if self.limbs[bit / 32] & (1 << (bit % 32)) != 0 {
                value |= 1u128 << (bit - start);
            }
        }
        if bits < 128 { value <<= 128 - bits; }
        value
    }
}

pub fn run(core: &str) {
    let mut out = String::from("//! GENERATED by check/src/gen_grisu.rs; do not edit.\n//! Run relax-std-gen grisu <core dir> to regenerate.\n//! Port of real core's Grisu cached powers (MIT/Apache-2.0).\n\n#[rustfmt::skip]\npub(super) static CACHED_POW10: [(u64, i16, i16); 81] = [\n");
    // Reference: for k >= 0, f=10^k, e=0; otherwise
    // f=floor(2^(80-4*k)/10^(-k)), e=4*k-80. Round its top 64 bits.
    for k in (-308i32..=332).step_by(8) {
        let mut power = Big::one();
        for _ in 0..k.unsigned_abs() { power.mul_small(10); }
        let (f, e) = if k < 0 {
            (Big::divide_power_two((80 - 4*k) as usize, &power), 4*k - 80)
        } else {
            (power, 0)
        };
        let normalized = f.normalized();
        let rounded = (normalized >> 64) as u64 + ((normalized >> 63) as u64 & 1);
        writeln!(out, "    (0x{:016x}, {}, {}),", rounded, e + f.bits() as i32 - 64, k).unwrap();
    }
    out.push_str("];\n");
    std::fs::write(std::path::Path::new(core).join("fmt/float/grisu_table.rs"), out).unwrap();
}
