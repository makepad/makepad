//! Item expansion for the file-selection outline. Shares the parser's resolver,
//! matcher, builtins and native macro host; ordinary function bodies stay tokens.
use super::*;
use std::collections::BTreeSet;
use std::sync::Arc;

pub(crate) struct Surface {
    /// The expansion text appended to the input's bytes (`text` is the whole): empty for a file
    /// whose expansion produced none, so the input is not copied.
    pub ext: Vec<u8>,
    pub toks: Vec<Tok>,
    pub unknown: BTreeSet<(String, String)>,
    /// Body openings the parser must collect eagerly (nested items or macro output).
    pub eager_bodies: BTreeSet<u32>,
    pub items: Vec<crate::preload::rs_items::Item>,
    pub used: crate::macros::MacroUse,
    pub reuse: Arc<crate::parse_work::Reuse>,
}

impl Surface {
    /// The expanded file's bytes: `input` (what `expand` was given) followed by the expansion text.
    pub(crate) fn text<'a>(&'a self, input: &'a [u8]) -> std::borrow::Cow<'a, [u8]> {
        if self.ext.is_empty() { std::borrow::Cow::Borrowed(input) }
        else { std::borrow::Cow::Owned([input, &self.ext[..]].concat()) }
    }
}

pub(crate) fn expand<'a>(src: &'a [u8], toks: impl Into<super::lazy_bodies::Toks<'a>>, edition: u16,
    ctx: std::rc::Rc<crate::builtins::FileCtx>, table: Arc<crate::macros::MacroTable>,
) -> Surface {
    let reuse = crate::parse_work::Session::new(Arc::default());
    let toks: super::lazy_bodies::Toks<'_> = toks.into();
    outline(Parser::new(&ctx.cfg.session, src, toks, edition), ctx.clone(), table, reuse)
}

/// Declaration expansion has a distinct contract and never contributes executable
/// expansions to parse reuse. The normal parser supplies cfg and macro scope.
pub(crate) fn expand_declarations(input: &crate::builtins::Expansion, edition: u16,
    ctx: std::rc::Rc<crate::builtins::FileCtx>, table: Arc<crate::macros::MacroTable>,
) -> Surface {
    crate::macro_reg::with_declarations(|| {
        let mut toks = super::lazy_bodies::Toks::from(&input.toks[..]);
        let end = input.text.len() as u32;
        toks.push(Tok { kind: T::Eof, lo: end, hi: end });
        expand(input.text.as_bytes(), toks, edition, ctx, table)
    })
}

fn outline(mut p: Parser<'_>, ctx: std::rc::Rc<crate::builtins::FileCtx>, table: Arc<crate::macros::MacroTable>,
    reuse: crate::parse_work::Session,
) -> Surface {
    let src = p.src;
    p.krate = ctx.krate.clone();
    p.bctx = Some(ctx.clone());
    // Includes in declaration discovery need the same file-aware macro spans as parsing.
    p.sources = Some(Arc::default());
    p.macros = Some(crate::macros::MacroScope::new(table));
    let mut unknown = BTreeSet::new();
    let mut tokens = Vec::new();
    let mut eager_bodies = BTreeSet::new();
    if let Err(e) = p.outline_items(T::Eof, &mut tokens, &mut unknown, &mut eager_bodies) {
        unknown.insert(("syntax".into(), e.msg));
        let end = p.toks.iter().position(|t| t.kind == T::Eof).unwrap_or(p.toks.len());
        tokens = p.toks.range(0, end).into_owned();
    }
    let ext = p.ext.view().contiguous().into_owned();
    let joined;
    let text: &[u8] = if ext.is_empty() { src } else {
        let mut all = Vec::with_capacity(src.len() + ext.len());
        all.extend_from_slice(src);
        all.extend_from_slice(&ext);
        joined = all;
        &joined
    };
    let toks = crate::preload::configured_tokens(text, &tokens, &ctx.cfg);
    let mut items = Vec::new();
    crate::preload::rs_items::split(text, &toks, 0, toks.len(), &ctx.module_path, &mut items);
    Surface { ext, toks, unknown, eager_bodies, items, used: p.macros.take().unwrap().finish(), reuse: reuse.finish() }
}

impl Parser<'_> {
    fn outline_items(&mut self, end: T, out: &mut Vec<Tok>, unknown: &mut BTreeSet<(String, String)>, eager_bodies: &mut BTreeSet<u32>) -> PResult<()> {
        let output_start = out.len();
        while self.kind() != end && self.kind() != T::Eof {
            if self.eat(T::Semi) { out.push(self.toks.at(self.pos - 1)); continue; }
            let start = self.pos;
            // A disabled file/module must not invoke macros, including those
            // generated by another expansion. Configure before expansion just
            // as the full parser does, not only when indexing the output.
            if self.kind() == T::Pound && self.nth(1) == T::Not && self.nth(2) == T::OpenBracket {
                let mut attrs = Vec::new();
                self.inner_attrs(&mut attrs)?;
                if !self.cfg_active(&attrs) {
                    out.truncate(output_start);
                    while self.kind() != end && self.kind() != T::Eof {
                        self.pos = if matches!(self.kind(), T::OpenBrace | T::OpenParen | T::OpenBracket) {
                            self.outline_close(self.pos)? + 1
                        } else { self.pos + 1 };
                    }
                    return Ok(());
                }
                out.extend_from_slice(&self.toks.range(start, self.pos));
                continue;
            }
            let attrs = self.outer_attrs()?;
            let head = self.pos;
            if self.kind() == T::Eof || self.kind() == end { break; }
            let stop = self.outline_item_end()?;
            if !self.cfg_active(&attrs) { self.pos = stop; continue; }
            if self.is_word(0, b"macro_rules") && self.nth(1) == T::Not {
                self.pos += 2;
                let name = self.ident_tok()?;
                let (_, range) = self.delim_tt()?;
                let exported = attrs.iter().any(|a| self.tok_text(self.toks.at(a.toks.lo as usize)) == b"macro_export");
                let local_inner = attrs.iter().any(|a| (a.toks.lo..a.toks.hi).any(|i| self.tok_text(self.toks.at(i as usize)) == b"local_inner_macros"));
                self.define_rules(name, range, exported, local_inner)?;
                self.eat(T::Semi);
                out.extend_from_slice(&self.toks.range(start, self.pos));
                continue;
            }
            if self.mac_ahead() {
                let path = self.path(true)?;
                let name = self.ast.segs(path.segs).last().map(|s| String::from_utf8_lossy(self.bytes(s.name.lo, s.name.hi)).into_owned()).unwrap_or_default();
                let def = self.rules_macro(&path);
                self.expect(T::Not)?;
                let (_, range) = self.delim_tt()?;
                self.eat(T::Semi);
                let after = self.pos;
                let can_expand = def.as_ref().is_some_and(|d| d.builtin < crate::builtins::HOSTED
                    || crate::macro_reg::outline_native(&d.name, crate::macro_reg::Kind::Bang));
                if can_expand {
                    if self.session.runtime.profile { eprintln!("rs-outline-expand: {:?} macro {name:?}", self.bctx.as_ref().map(|c| &c.path)); }
                    let before = out.len();
                    let result = self.expand_call(def.as_ref().unwrap(), range, self.toks.at(head).lo)
                        .and_then(|at| self.in_expansion(at, |p| p.outline_items(T::Eof, out, unknown, eager_bodies)));
                    if let Err(e) = result {
                        out.truncate(before);
                        out.extend_from_slice(&self.toks.range(start, after));
                        unknown.insert((format!("macro {name}"), e.msg));
                    }
                } else {
                    out.extend_from_slice(&self.toks.range(start, after));
                    unknown.insert((format!("macro {name}"), "no outline expander".into()));
                }
                self.pos = after;
                continue;
            }
            if let Some(k) = crate::builtins::attr_macro_at(self, &attrs) {
                let attr = &attrs[k];
                let mut name_at = attr.toks.lo as usize;
                while name_at + 2 < attr.toks.hi as usize && self.toks.at(name_at + 1).kind == T::PathSep { name_at += 2; }
                let name = String::from_utf8_lossy(self.tok_text(self.toks.at(name_at))).into_owned();
                if crate::macro_reg::outline_native(&name, crate::macro_reg::Kind::Attr) {
                    let x = crate::builtins::expand_attr_macro(self, attr, start, stop).map_err(|(pos, msg)| PErr { pos, msg })?;
                    self.pos = stop;
                    self.append_origins(&x, self.toks.at(head).lo);
                    let at = self.expand_toks(&x.text, &x.toks, self.toks.at(head).lo);
                    self.in_expansion(at, |p| p.outline_items(T::Eof, out, unknown, eager_bodies))?;
                    continue;
                }
                unknown.insert((format!("attribute {name}"), "unlinked attribute macro".into()));
            }
            // Only module, trait, impl and foreign scopes contain item-level
            // invocations. Struct fields and executable bodies are copied once.
            let mut keyword = head;
            while keyword < stop {
                match self.toks.at(keyword).kind {
                    T::KwPub if self.toks.get(keyword + 1).is_some_and(|t| t.kind == T::OpenParen) => keyword = self.outline_close(keyword + 1)? + 1,
                    T::KwPub | T::KwUnsafe | T::KwAsync => keyword += 1,
                    _ if self.tok_text(self.toks.at(keyword)) == b"default" => keyword += 1,
                    _ => break,
                }
            }
            // Use the parser's own eligibility decision in the same macro scope.
            // Collection exposes constants/statics emitted inside an eager body;
            // check can evaluate them (and thereby compile their enclosing owner)
            // even when no ordinary call demands that function.
            self.pos = keyword;
            if self.fn_ahead() {
                let open = (keyword..stop).find(|&i| self.toks.at(i).kind == T::OpenBrace
                    && self.outline_close(i).ok() == Some(stop - 1));
                if let Some(open) = open {
                    self.pos = open;
                    if !matches!(self.body_outline(), BodyOutline::Deferred(_)) {
                        eager_bodies.insert(self.toks.at(open).lo);
                    }
                }
            }
            self.pos = head;
            let kind = self.toks.at(keyword).kind;
            let nested = matches!(kind, T::KwMod | T::KwTrait | T::KwImpl)
                || kind == T::KwExtern && self.toks.get(keyword + 1).is_some_and(|t| t.kind != T::KwCrate)
                    && !self.toks.range(keyword, stop).iter().any(|t| t.kind == T::KwFn);
            if nested {
                let open = (keyword..stop).find(|&i| self.toks.at(i).kind == T::OpenBrace);
                if let Some(open) = open {
                    out.extend_from_slice(&self.toks.range(start, open + 1));
                    if kind == T::KwMod {
                        self.mod_stack.push(String::from_utf8_lossy(self.tok_text(self.toks.at(keyword + 1))).into_owned());
                    }
                    self.pos = open + 1;
                    self.outline_items(T::CloseBrace, out, unknown, eager_bodies)?;
                    out.push(self.expect(T::CloseBrace)?);
                    if kind == T::KwMod { self.mod_stack.pop(); }
                    if self.pos < stop { out.extend_from_slice(&self.toks.range(self.pos, stop)); }
                } else { out.extend_from_slice(&self.toks.range(start, stop)); }
            } else if matches!(kind, T::KwConst | T::KwStatic) && !self.fn_ahead_from(keyword - head) {
                out.extend_from_slice(&self.toks.range(start, head));
                self.pos = head;
                self.outline_initializer(stop, out, unknown)?;
            } else {
                out.extend_from_slice(&self.toks.range(start, stop));
            }
            if kind == T::KwUse {
                self.pos = keyword + 1;
                let global = self.eat(T::PathSep);
                let tree = self.use_tree()?;
                self.record_use(global, &tree);
            }
            self.pos = stop;
            let mut linked = true;
            for attr in &attrs {
                let lo = attr.toks.lo as usize;
                let hi = attr.toks.hi as usize;
                if lo == hi || self.tok_text(self.toks.at(lo)) != b"derive" { continue; }
                for i in lo + 1..hi {
                    if !matches!(self.toks.at(i).kind, T::Ident | T::RawIdent)
                        || self.toks.get(i + 1).is_some_and(|token| token.kind == T::PathSep) { continue; }
                    let name = String::from_utf8_lossy(self.tok_text(self.toks.at(i))).into_owned();
                    if (crate::macro_reg::has_derive(&name) || crate::macro_reg::declaring() && crate::parser::derive::trait_path(&name).is_none())
                        && !crate::macro_reg::outline_native(&name, crate::macro_reg::Kind::Derive) {
                        unknown.insert((format!("derive {name}"), "no source-matched declaration/outline contract".into()));
                        linked = false;
                    }
                }
            }
            if linked && !attrs.is_empty() {
                match crate::builtins::derive_items(self, &attrs, start, stop) {
                    Ok(Some(x)) => {
                        if self.session.runtime.profile { eprintln!("rs-outline-expand: {:?} derive", self.bctx.as_ref().map(|c| &c.path)); }
                        self.append_origins(&x, self.toks.at(head).lo);
                        let at = self.expand_toks(&x.text, &x.toks, self.toks.at(head).lo);
                        self.in_expansion(at, |p| p.outline_items(T::Eof, out, unknown, eager_bodies))?;
                    }
                    Ok(None) => {}
                    Err((_, error)) => { unknown.insert(("derive".into(), error)); }
                }
            }
        }
        Ok(())
    }

    /// Constant initializers are observable as soon as their file is collected.
    /// Expand their expression macros with the real matcher: a path argument may
    /// name generated function pointers absent from the invocation's spelling.
    fn outline_initializer(&mut self, end: usize, out: &mut Vec<Tok>, unknown: &mut BTreeSet<(String, String)>) -> PResult<()> {
        while self.pos < end && self.kind() != T::Eof {
            let start = self.pos;
            if self.is_word(0, b"macro_rules") && self.nth(1) == T::Not {
                let stop = self.outline_item_end()?;
                out.extend_from_slice(&self.toks.range(start, stop));
                self.pos = stop;
                unknown.insert(("initializer macro definition".into(), "nested textual scope".into()));
                continue;
            }
            if !self.mac_ahead() {
                out.push(self.toks.at(self.pos));
                self.pos += 1;
                continue;
            }
            let path = self.path(true)?;
            let name = self.ast.segs(path.segs).last().map(|s| String::from_utf8_lossy(self.bytes(s.name.lo, s.name.hi)).into_owned()).unwrap_or_default();
            let def = self.rules_macro(&path);
            self.expect(T::Not)?;
            let (_, range) = self.delim_tt()?;
            let after = self.pos;
            let can_expand = def.as_ref().is_some_and(|d| d.builtin < crate::builtins::HOSTED
                || crate::macro_reg::outline_native(&d.name, crate::macro_reg::Kind::Bang));
            if can_expand {
                let before = out.len();
                let result = self.expand_call(def.as_ref().unwrap(), range, self.toks.at(start).lo)
                    .and_then(|at| self.in_expansion(at, |p| p.outline_initializer(p.toks.len(), out, unknown)));
                if let Err(error) = result {
                    out.truncate(before);
                    out.extend_from_slice(&self.toks.range(start, after));
                    unknown.insert((format!("initializer macro {name}"), error.msg));
                }
            } else {
                out.extend_from_slice(&self.toks.range(start, after));
                // Parser-owned expression builtins have no MacroRef and their
                // implicit language dependencies are already demand seeds.
                if def.is_some() || !crate::program::BUILTIN_MACROS.contains(&name.as_str()) {
                    unknown.insert((format!("initializer macro {name}"), "no outline expander".into()));
                }
            }
            self.pos = after;
        }
        Ok(())
    }

    fn outline_close(&self, open: usize) -> PResult<usize> {
        let mut depth = 0usize;
        for at in open..self.toks.len() {
            match self.toks.at(at).kind {
                T::OpenBrace | T::OpenParen | T::OpenBracket => depth += 1,
                T::CloseBrace | T::CloseParen | T::CloseBracket => {
                    depth = depth.saturating_sub(1);
                    if depth == 0 { return Ok(at); }
                }
                T::Eof => break,
                _ => {}
            }
        }
        Err(PErr { pos: self.toks.at(open).lo, msg: "unclosed outline group".into() })
    }

    fn outline_item_end(&self) -> PResult<usize> {
        let mut at = self.pos;
        let mut semicolon = false;
        let mut angles = 0i32;
        while at < self.toks.len() {
            match self.toks.at(at).kind {
                T::Lt => angles += 1,
                T::Gt => angles = (angles - 1).max(0),
                T::Shr => angles = (angles - 2).max(0),
                T::KwUse | T::KwStatic | T::KwType => semicolon = true,
                T::Eq if angles == 0 => semicolon = true,
                T::KwFn => semicolon = false,
                T::Semi => return Ok(at + 1),
                T::CloseBrace | T::Eof => return Ok(at),
                T::OpenParen | T::OpenBracket => at = self.outline_close(at)?,
                T::OpenBrace => {
                    at = self.outline_close(at)?;
                    if !semicolon && angles == 0 { return Ok(at + 1); }
                }
                _ => {}
            }
            at += 1;
        }
        self.err("incomplete outline item")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn inner_cfg_precedes_item_macro_expansion() {
        let session = Arc::new(crate::Session::default());
        for source in [
            "#![cfg(test)] absent!();",
            "mod nested { #![cfg_attr(not(test), cfg(any()))] absent!(); }",
            "macro_rules! nested { () => { mod generated { #![cfg(test)] absent!(); } }; } nested!();",
        ] {
            for test in [false, true] {
                let mut cfg = crate::cfg::CfgSet::host(&session, &[]);
                if test { cfg.set.push("test".into()); }
                let mut tokens = Vec::new();
                assert!(crate::lexer::lex(source.as_bytes(), 2021, &mut tokens).is_ok());
                let context = std::rc::Rc::new(crate::builtins::FileCtx::new("probe", "probe.rs", "probe", &cfg));
                let surface = expand(source.as_bytes(), tokens, 2021, context, Arc::default());
                assert_eq!(surface.unknown.is_empty(), !test, "{source}: {:?}", surface.unknown);
            }
        }
    }
}
