#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct PreContact {
    pub dist: f64,
    pub pos: [f64; 3],
    pub normal: [f64; 3],
    pub tangent: [f64; 3],
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Contact {
    pub dist: f64,
    pub pos: [f64; 3],
    pub frame: [f64; 9],
    pub includemargin: f64,
    pub friction: [f64; 5],
    pub solref: [f64; NREF],
    pub solreffriction: [f64; NREF],
    pub solimp: [f64; NIMP],
    pub adhesion: f64,
    pub surfacevel: [f64; 3],
    pub mu: f64,
    pub h: [f64; 36],
    pub dim: i32,
    pub geom1: i32,
    pub geom2: i32,
    pub geom: [i32; 2],
    pub flex: [i32; 2],
    pub elem: [i32; 2],
    pub vert: [i32; 2],
    pub exclude: i32,
    pub efc_address: i32,
}

